/// A name made of the characters LLVM allows in an unquoted identifier.
/// `call` as an `invoke` (without its destinations), if the callee may
/// panic: anything but intrinsics and the runtime's functions that never do.
fn as_invoke(line: &str) -> Option<String> {
    let at = line.find("call ")?;
    let before = &line[..at];
    if !(before.is_empty() || before.ends_with("= ")) {
        return None;
    }
    let rest = &line[at + 5..];
    let callee_at = rest.find(['@', '%'])?;
    let callee = &rest[callee_at..];
    const NEVER: &[&str] = &[
        "@llvm.", "@tarn.release.", "@tarn.dup.", "@tarn.drop.", "@tarn.fields.", "@tarn.mem.", "@tarn_alloc(", "@tarn_free(", "@tarn_drop_slow(",
        "@tarn_release_cyclic(", "@tarn_cyclic_free(", "@tarn_handle_free(", "@tarn_print_", "@tarn_str_free(", "@tarn_list_free(", "@tarn_list_new(",
        "@tarn_list_push_slot(", "@tarn_xfer_at(", "@tarn_xfer_done(", "@tarn_str_concat(", "@tarn_str_append_owned(", "@tarn_int_to_str(",
        "@tarn_float_to_str(", "@tarn_bool_to_str(", "@tarn_str_eq(", "@tarn_str_cmp(", "@tarn_map_free(", "@tarn_map_new(",
    ];
    if NEVER.iter().any(|n| callee.starts_with(n)) {
        return None;
    }
    Some(format!("{before}invoke {rest}"))
}

fn llvm_name(name: &str) -> String {
    name.chars()
        .filter(|c| *c != ' ')
        .map(|c| if c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | '$' | '-') { c } else { '.' })
        .collect()
}

fn llty(t: &Type) -> &'static str {
    match t {
        Type::Int => "i64",
        Type::Float => "double",
        Type::Bool => "i1",
        Type::Str | Type::Bytes | Type::List(_) | Type::Map(..) | Type::Struct(_) | Type::Enum(_, true) | Type::Func(..) | Type::Iface(_) | Type::Handle => "ptr",
        // An enum without data is just the number of its variant.
        Type::Enum(_, false) => "i64",
        Type::Unit => "void",
        // A nullable reference is a pointer that may be null; a nullable
        // primitive is a (has-value flag, value) pair, kept in registers.
        Type::Nullable(inner) => match **inner {
            Type::Int | Type::Enum(_, false) => "{ i1, i64 }",
            Type::Float => "{ i1, double }",
            Type::Bool => "{ i1, i1 }",
            _ => "ptr",
        },
        Type::Error | Type::Null | Type::Param(_) => unreachable!("{t:?} reached codegen"),
    }
}

/// The C type of a runtime function's parameter or result (`stdlib::RT`):
/// as `llty`, but a `Bool` crosses as an `i64`.
fn rt_llty(t: &str) -> &'static str {
    match crate::stdlib::parse_type(t) {
        Type::Bool => "i64",
        Type::Unit => "void",
        t => {
            assert!(!is_pair(&t), "runtime functions can't return a nullable primitive");
            llty(&t)
        }
    }
}

/// A nullable primitive (stored as a `{ i1, T }` pair)?
fn is_pair(t: &Type) -> bool {
    matches!(t, Type::Nullable(inner) if inner.is_primitive() && **inner != Type::Str)
}

/// Size in bytes of a list element of this type.
fn elem_size(t: &Type) -> u64 {
    match t {
        Type::Bool => 1,
        Type::Nullable(inner) if **inner == Type::Bool => 2,
        t if is_pair(t) => 16,
        _ => 8,
    }
}

fn list_elem(t: &Type) -> Type {
    match t {
        Type::List(e) => (**e).clone(),
        _ => unreachable!("not a list: {t:?}"),
    }
}

/// A name for a reference-counted type, used in its release/drop functions.
fn mangle(t: &Type) -> String {
    match t {
        Type::Str => "str".into(),
        Type::Bytes => "bytes".into(),
        Type::List(e) => format!("list.{}", mangle(e)),
        Type::Map(k, v) => format!("map.{}.{}", mangle(k), mangle(v)),
        Type::Struct(id) => format!("s{id}"),
        Type::Enum(id, _) => format!("e{id}"),
        Type::Int => "int".into(),
        Type::Float => "float".into(),
        Type::Bool => "bool".into(),
        Type::Nullable(inner) => format!("opt.{}", mangle(inner)),
        Type::Unit => "unit".into(),
        Type::Func(ps, r) => format!("fn.{}.to.{}.end", ps.iter().map(mangle).collect::<Vec<_>>().join("."), mangle(r)),
        Type::Iface(id) => format!("i{id}"),
        Type::Handle => "handle".into(),
        _ => unreachable!("no runtime representation: {t:?}"),
    }
}

fn map_kv(t: &Type) -> (Type, Type) {
    match t {
        Type::Map(k, v) => ((**k).clone(), (**v).clone()),
        _ => unreachable!("not a map: {t:?}"),
    }
}

/// How the runtime treats map keys of type `k`: 0 for numbers (also
/// `Bool` and enums without data, widened to `i64`), 1 for strings, 2 for
/// values of user types (hashed and compared through generated functions).
fn key_kind(k: &Type) -> i64 {
    match k {
        Type::Int | Type::Bool | Type::Enum(_, false) => 0,
        Type::Str => 1,
        _ => 2,
    }
}

fn key_llty(k: &Type) -> &'static str {
    if key_kind(k) == 0 { "i64" } else { "ptr" }
}

/// The LLVM type of one map entry: `{ hash, key, value }`.
fn entry_ty(k: &Type, v: &Type) -> String {
    format!("{{ i64, {}, {} }}", key_llty(k), llty(v))
}

/// The count every string literal starts with: so large it never reaches zero.
const RC_IMMORTAL: i64 = 1 << 62;

fn escape_bytes(b: &[u8]) -> String {
    let mut s = String::new();
    for &c in b {
        if (0x20..0x7f).contains(&c) && c != b'"' && c != b'\\' {
            s.push(c as char);
        } else {
            let _ = write!(s, "\\{c:02X}");
        }
    }
    s
}

fn float_const(v: f64) -> String {
    format!("0x{:016X}", v.to_bits())
}

/// The body of a `void (ptr %p)` function that runs `code[k]` for a value of
/// variant `k` of an enum with data (the tag is at offset 8).
fn variant_switch(code: &[String]) -> String {
    let cases: Vec<String> = (1..code.len()).map(|k| format!("i64 {k}, label %v{k}")).collect();
    let mut out = format!("entry:\n  %tagp = getelementptr inbounds i8, ptr %p, i64 8\n  %tag = load i64, ptr %tagp\n  switch i64 %tag, label %v0 [ {} ]\n", cases.join(" "));
    for (k, c) in code.iter().enumerate() {
        let _ = write!(out, "v{k}:\n{c}  ret void\n");
    }
    out
}

struct Codegen<'a> {
    prog: &'a Program,
    /// Per struct or enum: its name in LLVM types (`%struct.<name>`).
    type_names: Vec<String>,
    sources: &'a SourceMap<'a>,
    /// The function being generated.
    f: &'a Func,
    /// Inside a `track_caller` function: the caller's location arguments.
    caller_loc: Option<String>,
    strings: HashMap<String, String>,
    globals: String,
    // per-function state
    body: String,
    allocas: String,
    tmp: usize,
    label: usize,
    cur_label: String,
    terminated: bool,
    /// TBAA alias classes, by name, in creation order.
    tbaa: Vec<String>,
    /// Types that need release/drop functions, in first-use order.
    rc_types: Vec<Type>,
    /// Memoized `cycles::is_cyclic`.
    cyclic: HashMap<Type, bool>,
    /// Data-less variants of enums with data, emitted as immortal singletons: (enum, variant).
    units: Vec<(StructId, usize)>,
    /// Enums without data whose variant names are needed (`print`, f-strings).
    name_tables: Vec<StructId>,
    /// Map types whose type records (and `clear` functions) are needed.
    map_types: Vec<Type>,
    /// List types whose `clear()` function is needed.
    list_clears: Vec<Type>,
    /// How many of `rc_types` already have their functions.
    rc_done: usize,
    /// Function values are used: the dispatchers are needed (and emitted, once).
    closure_rt: bool,
    closure_rt_done: bool,
    /// Closure code used as a constant function value (a global each).
    fn_consts: Vec<FuncId>,
    /// Lambdas whose closures are built (their structs), and how many have their functions.
    closure_classes: Vec<StructId>,
    closures_done: usize,
    /// Boxes whose method table (a global) has been emitted.
    vtables: Vec<StructId>,
    /// Types whose tag (a global telling a box's contents apart) is emitted.
    type_tags: Vec<String>,
    /// Types matched inside interface values (`case Circle`), each with a
    /// function finding the box that holds one, and how many are emitted.
    box_finders: Vec<Type>,
    box_finders_done: usize,
    /// Types whose `tarn.xfer` (move or copy to another task), `tarn.dup`
    /// and `tarn.slot.release` functions are needed (see `tasks.rs`), and
    /// how many are emitted; and the task and lock callbacks.
    xfer_types: Vec<Type>,
    xfer_done: usize,
    dup_types: Vec<Type>,
    dup_done: usize,
    slot_types: Vec<Type>,
    slot_done: usize,
    sync_helpers: Vec<(String, String)>,
    sync_done: usize,
    cstrs: usize,
    /// The program starts tasks, so a panic can unwind a task's stack: calls
    /// that may panic become `invoke`s whose landing pad releases what the
    /// function holds there (`Func::cleanups`). Without tasks a panic ends
    /// the program, so there's nothing to release.
    unwinds: bool,
    /// The landing pad for the statement being generated, if it holds anything.
    cleanup: Option<String>,
    /// This function's landing pads: what each releases, and its label.
    lpads: Vec<(Vec<(VarId, u32)>, String)>,
}

impl<'a> Codegen<'a> {
    // ---------- emission helpers ----------

    fn fresh(&mut self) -> String {
        self.tmp += 1;
        format!("%t{}", self.tmp)
    }

    fn new_label(&mut self, hint: &str) -> String {
        self.label += 1;
        format!("{hint}{}", self.label)
    }

    /// Emit an instruction. If the current block already ended (e.g. after a
    /// `return`), the instruction goes into a fresh unreachable block.
    fn emit(&mut self, s: impl AsRef<str>) {
        if self.terminated {
            let l = self.new_label("dead");
            let _ = writeln!(self.body, "{l}:");
            self.cur_label = l;
            self.terminated = false;
        }
        // A call that may panic, where this function holds references: an
        // `invoke` that releases them if the task unwinds.
        if let Some(lp) = self.cleanup.clone()
            && let Some(inv) = as_invoke(s.as_ref())
        {
            let ok = self.new_label("ok");
            let _ = writeln!(self.body, "  {inv} to label %{ok} unwind label %{lp}\n{ok}:");
            self.cur_label = ok;
            return;
        }
        self.body.push_str("  ");
        self.body.push_str(s.as_ref());
        self.body.push('\n');
    }

    /// The landing pad releasing `held` (made once per function).
    fn lpad_label(&mut self, held: &[(VarId, u32)]) -> String {
        if let Some((_, l)) = self.lpads.iter().find(|(h, _)| h == held) {
            return l.clone();
        }
        let l = format!("lpad{}", self.lpads.len());
        self.lpads.push((held.to_vec(), l.clone()));
        l
    }

    /// The landing pads of the function just generated.
    fn landing_pads(&mut self) -> String {
        let mut out = String::new();
        for (k, (held, label)) in std::mem::take(&mut self.lpads).into_iter().enumerate() {
            let _ = writeln!(out, "{label}:\n  %lp{k} = landingpad {{ ptr, i32 }} cleanup");
            // (Latest variables first, as when a block ends.)
            for (j, (v, n)) in held.iter().rev().enumerate() {
                let ty = self.f.vars[*v].ty.clone();
                let rel = self.release_fn(&ty);
                let _ = writeln!(out, "  %lp{k}.{j} = load ptr, ptr %v{v}");
                for _ in 0..*n {
                    let _ = writeln!(out, "  call void {rel}(ptr %lp{k}.{j})");
                }
            }
            let _ = writeln!(out, "  resume {{ ptr, i32 }} %lp{k}");
        }
        out
    }

    fn emit_term(&mut self, s: impl AsRef<str>) {
        self.emit(s);
        self.terminated = true;
    }

    fn br(&mut self, label: &str) {
        if !self.terminated {
            self.emit_term(format!("br label %{label}"));
        }
    }

    fn start_block(&mut self, label: &str) {
        self.br(label);
        let _ = writeln!(self.body, "{label}:");
        self.cur_label = label.to_string();
        self.terminated = false;
    }

    /// `, !tbaa !N` suffix for a memory access of the given alias class.
    fn tbaa(&mut self, class: &str) -> String {
        let i = match self.tbaa.iter().position(|c| c == class) {
            Some(i) => i,
            None => {
                self.tbaa.push(class.to_string());
                self.tbaa.len() - 1
            }
        };
        format!(", !tbaa !{}", 2 * i + 2)
    }

    fn elem_tbaa(&mut self, elem: &Type) -> String {
        if is_pair(elem) {
            return String::new(); // (TBAA tags describe scalar accesses)
        }
        let class = format!("list.elem.{}", llty(elem));
        self.tbaa(&class)
    }

    fn field_tbaa(&mut self, sid: StructId, idx: usize) -> String {
        if is_pair(&self.prog.structs[sid].fields[idx].ty) {
            return String::new();
        }
        let class = format!("field.{}.{idx}", self.type_names[sid]);
        self.tbaa(&class)
    }

    fn variant_tbaa(&mut self, sid: StructId, k: usize, i: usize) -> String {
        if is_pair(&self.prog.structs[sid].variants()[k].fields[i].ty) {
            return String::new();
        }
        let class = format!("variant.{}.{k}.{i}", self.type_names[sid]);
        self.tbaa(&class)
    }

    /// `%enum.Shape.Circle`
    fn variant_llty(&self, sid: StructId, k: usize) -> String {
        let s = &self.prog.structs[sid];
        format!("%enum.{}.{}", self.type_names[sid], s.variants()[k].name)
    }

    /// Does enum `sid` live on the heap (some variant carries data)?
    fn boxed(&self, sid: StructId) -> bool {
        self.prog.structs[sid].variants().iter().any(|v| !v.fields.is_empty())
    }

    /// The immortal singleton for a data-less variant of an enum with data.
    fn unit_value(&mut self, sid: StructId, k: usize) -> String {
        let name = format!("@tarn.unit.{sid}.{k}");
        if !self.units.contains(&(sid, k)) {
            self.units.push((sid, k));
            let _ = writeln!(self.globals, "{name} = internal global {{ i64, i64 }} {{ i64 {RC_IMMORTAL}, i64 {k} }}, align 8");
        }
        name
    }

    /// `[N x ptr]` of the variant names of a data-less enum, as Tarn strings.
    fn name_table(&mut self, sid: StructId) -> String {
        let name = format!("@tarn.names.{sid}");
        if !self.name_tables.contains(&sid) {
            self.name_tables.push(sid);
            let names: Vec<String> = self.prog.structs[sid].variants().iter().map(|v| v.name.clone()).collect();
            let entries: Vec<String> = names.iter().map(|n| format!("ptr {}", self.string_literal(n))).collect();
            let _ = writeln!(self.globals, "{name} = private constant [{} x ptr] [{}]", entries.len(), entries.join(", "));
        }
        name
    }

    /// `ptr file, i32 line, i32 col` arguments for runtime panics.
    fn loc(&self, span: Span) -> String {
        if let Some(caller) = &self.caller_loc {
            return caller.clone();
        }
        let (file, line, col) = self.sources.locate(span.start);
        format!("ptr @.file.{file}, i32 {line}, i32 {col}")
    }

    /// Branch to a cold panic block when `cond` is true.
    fn panic_if(&mut self, cond: &str, panic_call: String) {
        let bad = self.new_label("panic");
        let ok = self.new_label("ok");
        self.emit_term(format!("br i1 {cond}, label %{bad}, label %{ok}"));
        self.start_block(&bad);
        self.emit(panic_call);
        self.emit_term("unreachable");
        self.start_block(&ok);
    }

    fn string_literal(&mut self, s: &str) -> String {
        if let Some(name) = self.strings.get(s) {
            return name.clone();
        }
        let name = format!("@.str.{}", self.strings.len());
        let b = s.as_bytes();
        let _ = writeln!(
            self.globals,
            "{name} = private unnamed_addr global {{ i64, i64, i64, [{n} x i8] }} {{ i64 {RC_IMMORTAL}, i64 {n}, i64 {n}, [{n} x i8] c\"{}\" }}, align 8",
            escape_bytes(b),
            n = b.len()
        );
        self.strings.insert(s.to_string(), name.clone());
        name
    }

    fn var_ty(&self, v: VarId) -> &'static str {
        llty(&self.f.vars[v].ty)
    }

    // ---------- functions ----------

    fn function(&mut self, f: &'a Func) -> String {
        self.f = f;
        self.body.clear();
        self.allocas.clear();
        self.tmp = 0;
        self.label = 0;
        self.cur_label = "entry".into();
        self.terminated = false;
        self.caller_loc = f.track_caller.then(|| "ptr %caller.file, i32 %caller.line, i32 %caller.col".to_string());

        for (id, v) in f.vars.iter().enumerate() {
            if v.ty != Type::Unit {
                let _ = writeln!(self.allocas, "  %v{id} = alloca {}", llty(&v.ty));
            }
        }
        let mut params = Vec::new();
        for (i, &id) in f.params.iter().enumerate() {
            let ty = self.var_ty(id);
            params.push(format!("{ty} %a{i}"));
            self.emit(format!("store {ty} %a{i}, ptr %v{id}"));
        }
        if f.track_caller {
            params.push("ptr %caller.file, i32 %caller.line, i32 %caller.col".to_string());
        }
        self.lpads.clear();
        for (b, block) in f.blocks.iter().enumerate() {
            self.start_block(&format!("bb{b}"));
            for (i, s) in block.stmts.iter().enumerate() {
                let held = if self.unwinds { f.cleanups.get(b).and_then(|c| c.get(i)).filter(|c| !c.is_empty()).cloned() } else { None };
                self.cleanup = held.map(|h| self.lpad_label(&h));
                self.stmt(s);
                self.cleanup = None;
            }
            self.term(&block.term);
        }
        let personality = if self.lpads.is_empty() { "" } else { " personality ptr @__gcc_personality_v0" };
        let pads = self.landing_pads();
        let linkage = if f.exported { "" } else { "internal " };
        format!(
            "; {}\ndefine {linkage}{} @{}({}) #0{personality} {{\nentry:\n{}{}{pads}}}\n\n",
            f.name,
            llty(&f.ret),
            f.symbol,
            params.join(", "),
            self.allocas,
            self.body
        )
    }

    fn term(&mut self, t: &Term) {
        match t {
            Term::Goto(b) => self.emit_term(format!("br label %bb{b}")),
            Term::Branch(c, t, e) => {
                let c = self.operand(c);
                self.emit_term(format!("br i1 {c}, label %bb{t}, label %bb{e}"));
            }
            Term::Return(None) => self.emit_term("ret void"),
            Term::Return(Some(o)) => {
                let ty = llty(&self.f.operand_ty(o));
                let v = self.operand(o);
                self.emit_term(format!("ret {ty} {v}"));
            }
            Term::Unreachable => self.emit_term("unreachable"),
        }
    }

    // ---------- statements ----------

    fn stmt(&mut self, s: &Stmt) {
        match s {
            Stmt::Assign(v, r) => {
                let val = self.rvalue(r);
                let ty = self.var_ty(*v);
                self.emit(format!("store {ty} {val}, ptr %v{v}"));
            }
            Stmt::Eval(r) => {
                self.rvalue(r);
            }
            Stmt::Store { place, value, old } => {
                let v = self.operand(value);
                let (addr, ty, md) = match place {
                    Place::Field { obj, sid, idx } => {
                        let o = self.operand(&Operand::Var(*obj));
                        let p = self.fresh();
                        let sname = self.type_names[*sid].clone();
                        self.emit(format!("{p} = getelementptr inbounds %struct.{sname}, ptr {o}, i32 0, i32 {}", self.field_slot(*sid, *idx)));
                        let md = self.field_tbaa(*sid, *idx);
                        (p, self.prog.structs[*sid].fields[*idx].ty.clone(), md)
                    }
                    Place::Index { list, index, span } => {
                        let elem = list_elem(&self.f.vars[*list].ty);
                        let l = self.operand(&Operand::Var(*list));
                        let i = self.operand(index);
                        let p = self.list_elem_ptr(&l, &i, &elem, Some(*span));
                        let md = self.elem_tbaa(&elem);
                        (p, elem, md)
                    }
                };
                let lt = llty(&ty);
                if let Some(o) = old {
                    let cur = self.fresh();
                    self.emit(format!("{cur} = load {lt}, ptr {addr}{md}"));
                    self.emit(format!("store {lt} {cur}, ptr %v{o}"));
                }
                self.emit(format!("store {lt} {v}, ptr {addr}{md}"));
            }
            Stmt::Dup(v) => {
                let ty = self.f.vars[*v].ty.clone();
                let p = self.operand(&Operand::Var(*v));
                self.dup_value(&ty, &p);
            }
            Stmt::Drop(v) => {
                let ty = self.f.vars[*v].ty.clone();
                let p = self.operand(&Operand::Var(*v));
                let rel = self.release_fn(&ty);
                self.emit(format!("call void {rel}(ptr {p})"));
            }
            Stmt::KeepAlive(_) => {}
            Stmt::DropReuse(v, tok) => {
                // Last reference: release the fields and keep the memory as the
                // token. Otherwise just decrement, and the token is null.
                let ty = self.f.vars[*v].ty.clone();
                self.release_fn(&ty);
                let p = self.operand(&Operand::Var(*v));
                let md = self.tbaa("rc");
                let c = self.fresh();
                self.emit(format!("{c} = load i64, ptr {p}{md}"));
                let unique = self.fresh();
                self.emit(format!("{unique} = icmp eq i64 {c}, 1"));
                let lu = self.new_label("reuse.unique");
                let ls = self.new_label("reuse.shared");
                let ld = self.new_label("reuse.done");
                self.emit_term(format!("br i1 {unique}, label %{lu}, label %{ls}"));
                self.start_block(&lu);
                self.emit(format!("call void @tarn.fields.{}(ptr {p})", mangle(&ty)));
                self.br(&ld);
                self.start_block(&ls);
                let n = self.fresh();
                self.emit(format!("{n} = sub i64 {c}, 1"));
                self.emit(format!("store i64 {n}, ptr {p}{md}"));
                self.br(&ld);
                self.start_block(&ld);
                let t = self.fresh();
                self.emit(format!("{t} = phi ptr [ {p}, %{lu} ], [ null, %{ls} ]"));
                self.emit(format!("store ptr {t}, ptr %v{tok}"));
            }
        }
    }

    /// Add a reference to `p`, a value of type `ty` (which may be null if nullable).
    fn dup_value(&mut self, ty: &Type, p: &str) {
        let skip = if ty.is_nullable() {
            let null = self.fresh();
            self.emit(format!("{null} = icmp eq ptr {p}, null"));
            let (inc, skip) = (self.new_label("dup"), self.new_label("dup.done"));
            self.emit_term(format!("br i1 {null}, label %{skip}, label %{inc}"));
            self.start_block(&inc);
            Some(skip)
        } else {
            None
        };
        // A handle (task, channel, mutex...) can be reached from several tasks.
        if *ty.non_null() == Type::Handle {
            let old = self.fresh();
            self.emit(format!("{old} = atomicrmw add ptr {p}, i64 1 monotonic"));
            if let Some(skip) = skip {
                self.start_block(&skip);
            }
            return;
        }
        let md = self.tbaa("rc");
        let c = self.fresh();
        self.emit(format!("{c} = load i64, ptr {p}{md}"));
        let n = self.fresh();
        if self.is_cyclic(ty) {
            // Count in the upper bits; a new reference also marks it in use (black).
            let m = self.fresh();
            self.emit(format!("{m} = add i64 {c}, 8"));
            self.emit(format!("{n} = and i64 {m}, -4"));
        } else {
            self.emit(format!("{n} = add i64 {c}, 1"));
        }
        self.emit(format!("store i64 {n}, ptr {p}{md}"));
        if let Some(skip) = skip {
            self.start_block(&skip);
        }
    }

    // ---------- expressions ----------

    fn operand(&mut self, o: &Operand) -> String {
        match o {
            Operand::Var(v) => {
                let r = self.fresh();
                let ty = self.var_ty(*v);
                self.emit(format!("{r} = load {ty}, ptr %v{v}"));
                r
            }
            Operand::Int(v) => v.to_string(),
            Operand::Float(v) => float_const(*v),
            Operand::Bool(v) => v.to_string(),
            Operand::Str(s) => self.string_literal(s),
            Operand::Null(t) => if is_pair(t) { "zeroinitializer" } else { "null" }.to_string(),
        }
    }

    /// Returns a pointer to element `i` of `list`, with a bounds check when `span` is given.
    fn list_elem_ptr(&mut self, list: &str, i: &str, elem: &Type, span: Option<Span>) -> String {
        if let Some(span) = span {
            let len = self.list_len(list);
            let oob = self.fresh();
            self.emit(format!("{oob} = icmp uge i64 {i}, {len}"));
            let loc = self.loc(span);
            self.panic_if(&oob, format!("call void @tarn_panic_bounds(i64 {i}, i64 {len}, {loc})"));
        }
        let dp = self.fresh();
        self.emit(format!("{dp} = getelementptr inbounds %TarnList, ptr {list}, i32 0, i32 3"));
        let data = self.fresh();
        let md_data = self.tbaa("list.data");
        self.emit(format!("{data} = load ptr, ptr {dp}{md_data}"));
        let ep = self.fresh();
        self.emit(format!("{ep} = getelementptr inbounds {}, ptr {data}, i64 {i}", llty(elem)));
        ep
    }

    /// Reserve a slot at the end of `list`. The common case (spare capacity)
    /// is inlined; only growth calls into the runtime.
    fn push_slot(&mut self, list: &str, elem: &Type) -> String {
        let sz = elem_size(elem);
        let md_len = self.tbaa("list.len");
        let md_cap = self.tbaa("list.cap");
        let md_data = self.tbaa("list.data");
        let lenp = self.fresh();
        self.emit(format!("{lenp} = getelementptr inbounds %TarnList, ptr {list}, i32 0, i32 1"));
        let len = self.fresh();
        self.emit(format!("{len} = load i64, ptr {lenp}{md_len}"));
        let capp = self.fresh();
        self.emit(format!("{capp} = getelementptr inbounds %TarnList, ptr {list}, i32 0, i32 2"));
        let cap = self.fresh();
        self.emit(format!("{cap} = load i64, ptr {capp}{md_cap}"));
        let full = self.fresh();
        self.emit(format!("{full} = icmp eq i64 {len}, {cap}"));
        let grow = self.new_label("push.grow");
        let fast = self.new_label("push.fast");
        let done = self.new_label("push.done");
        self.emit_term(format!("br i1 {full}, label %{grow}, label %{fast}"));
        self.start_block(&grow);
        let slow = self.fresh();
        self.emit(format!("{slow} = call ptr @tarn_list_push_slot(ptr {list}, i64 {sz})"));
        self.br(&done);
        self.start_block(&fast);
        let dp = self.fresh();
        self.emit(format!("{dp} = getelementptr inbounds %TarnList, ptr {list}, i32 0, i32 3"));
        let data = self.fresh();
        self.emit(format!("{data} = load ptr, ptr {dp}{md_data}"));
        let quick = self.fresh();
        self.emit(format!("{quick} = getelementptr inbounds {}, ptr {data}, i64 {len}", llty(elem)));
        let newlen = self.fresh();
        self.emit(format!("{newlen} = add nsw i64 {len}, 1"));
        self.emit(format!("store i64 {newlen}, ptr {lenp}{md_len}"));
        self.br(&done);
        self.start_block(&done);
        let slot = self.fresh();
        self.emit(format!("{slot} = phi ptr [ {slow}, %{grow} ], [ {quick}, %{fast} ]"));
        slot
    }

    fn list_len(&mut self, list: &str) -> String {
        let lp = self.fresh();
        self.emit(format!("{lp} = getelementptr inbounds %TarnList, ptr {list}, i32 0, i32 1"));
        let len = self.fresh();
        let md = self.tbaa("list.len");
        self.emit(format!("{len} = load i64, ptr {lp}{md}"));
        len
    }

    /// The (always-inlined) function that drops one reference to a value of type `t`.
    fn release_fn(&mut self, t: &Type) -> String {
        if !self.rc_types.contains(t) {
            self.rc_types.push(t.clone());
        }
        format!("@tarn.release.{}", mangle(t))
    }

    /// What frees a value of type `t` once its count reaches zero.
    fn drop_fn(&mut self, t: &Type) -> String {
        match t {
            Type::Str | Type::Bytes => "@tarn_str_free".into(),
            Type::List(e) if !is_ref(e) => "@tarn_list_free".into(),
            Type::Map(k, v) if !is_ref(k) && !is_ref(v) => "@tarn_map_free".into(),
            _ => format!("@tarn.drop.{}", mangle(t)),
        }
    }

    /// Release and drop functions for every reference-counted type used.
    fn is_cyclic(&mut self, t: &Type) -> bool {
        if let Some(&c) = self.cyclic.get(t) {
            return c;
        }
        let c = crate::cycles::is_cyclic(t, &self.prog.structs);
        self.cyclic.insert(t.clone(), c);
        c
    }

    /// Release, trace and free functions plus the type info record for a type
    /// that can be part of a cycle (see `tarn_collect_cycles` in the runtime).
    fn cyclic_functions(&mut self, t: &Type, out: &mut String) {
        let m = mangle(t);
        let _ = writeln!(
            out,
            "define internal void @tarn.release.{m}(ptr %p) #2 {{\n  call void @tarn_release_cyclic(ptr %p, ptr @tarn.ti.{m})\n  ret void\n}}\n"
        );
        let _ = writeln!(
            out,
            "@tarn.ti.{m} = internal constant {{ ptr, ptr, ptr, ptr }} {{ ptr @tarn.trace.{m}, ptr @tarn.drop.{m}, ptr @tarn.white.{m}, ptr @tarn.mem.{m} }}\n"
        );
        match t {
            Type::Struct(sid) => {
                let s = &self.prog.structs[*sid];
                let sname = self.type_names[*sid].clone();
                let fields: Vec<(usize, Type)> =
                    s.fields.iter().enumerate().filter(|(_, f)| is_ref(&f.ty)).map(|(i, f)| (i, f.ty.clone())).collect();
                let (mut trace, mut all, mut acyclic) = (String::new(), String::new(), String::new());
                for (k, (idx, fty)) in fields.iter().enumerate() {
                    let rel = self.release_fn(fty);
                    let load = format!(
                        "  %f{k}p = getelementptr inbounds %struct.{sname}, ptr %p, i32 0, i32 {}\n  %f{k} = load ptr, ptr %f{k}p\n",
                        idx + 1
                    );
                    let _ = writeln!(all, "{load}  call void {rel}(ptr %f{k})");
                    if self.is_cyclic(fty) {
                        // (a null child is skipped by the collector's visitors)
                        let _ = writeln!(trace, "{load}  call void %visit(ptr %f{k}, ptr @tarn.ti.{})", mangle(fty.non_null()));
                    } else {
                        let _ = writeln!(acyclic, "{load}  call void {rel}(ptr %f{k})");
                    }
                }
                let _ = writeln!(out, "define internal void @tarn.trace.{m}(ptr %p, ptr %visit) #0 {{\n{trace}  ret void\n}}\n");
                let _ = writeln!(
                    out,
                    "define internal void @tarn.drop.{m}(ptr %p) #0 {{\n{all}  call void @tarn_cyclic_free(ptr %p, ptr @tarn.ti.{m})\n  ret void\n}}\n"
                );
                let _ = writeln!(out, "define internal void @tarn.white.{m}(ptr %p) #0 {{\n{acyclic}  call void @tarn.mem.{m}(ptr %p)\n  ret void\n}}\n");
                let _ = writeln!(
                    out,
                    "define internal void @tarn.mem.{m}(ptr %p) #0 {{\n  %szp = getelementptr %struct.{sname}, ptr null, i32 1\n  %sz = ptrtoint ptr %szp to i64\n  call void @tarn_free(ptr %p, i64 %sz)\n  ret void\n}}\n"
                );
            }
            Type::List(e) => {
                // A cyclic list's elements are themselves cyclic, so the collector
                // accounts for all of them: freeing a garbage list frees only memory.
                let rel = self.release_fn(e);
                let em = mangle(e.non_null());
                let each = |action: &str| {
                    format!(
                        "entry:\n  %lenp = getelementptr inbounds %TarnList, ptr %p, i32 0, i32 1\n  %len = load i64, ptr %lenp\n  %dp = getelementptr inbounds %TarnList, ptr %p, i32 0, i32 3\n  %data = load ptr, ptr %dp\n  br label %cond\ncond:\n  %i = phi i64 [ 0, %entry ], [ %i1, %body ]\n  %c = icmp slt i64 %i, %len\n  br i1 %c, label %body, label %done\nbody:\n  %ep = getelementptr inbounds ptr, ptr %data, i64 %i\n  %e = load ptr, ptr %ep\n  {action}\n  %i1 = add i64 %i, 1\n  br label %cond\ndone:\n"
                    )
                };
                let _ = writeln!(
                    out,
                    "define internal void @tarn.trace.{m}(ptr %p, ptr %visit) #0 {{\n{}  ret void\n}}\n",
                    each(&format!("call void %visit(ptr %e, ptr @tarn.ti.{em})"))
                );
                let _ = writeln!(
                    out,
                    "define internal void @tarn.drop.{m}(ptr %p) #0 {{\n{}  call void @tarn_cyclic_free(ptr %p, ptr @tarn.ti.{m})\n  ret void\n}}\n",
                    each(&format!("call void {rel}(ptr %e)"))
                );
                let _ = writeln!(out, "define internal void @tarn.white.{m}(ptr %p) #0 {{\n  call void @tarn_list_free(ptr %p)\n  ret void\n}}\n");
                let _ = writeln!(out, "define internal void @tarn.mem.{m}(ptr %p) #0 {{\n  call void @tarn_list_free(ptr %p)\n  ret void\n}}\n");
            }
            Type::Enum(sid, true) => {
                let sid = *sid;
                let n = self.prog.structs[sid].variants().len();
                let (mut trace, mut all, mut acyclic, mut mem) = (Vec::new(), Vec::new(), Vec::new(), Vec::new());
                for k in 0..n {
                    let fields: Vec<Type> = self.prog.structs[sid].variants()[k].fields.iter().map(|f| f.ty.clone()).collect();
                    let mut t = String::new();
                    for (i, fty) in fields.iter().enumerate() {
                        if is_ref(fty) && self.is_cyclic(fty) {
                            let lt = self.variant_llty(sid, k);
                            let _ = writeln!(
                                t,
                                "  %v{k}f{i}p = getelementptr inbounds {lt}, ptr %p, i32 0, i32 {}\n  %v{k}f{i} = load ptr, ptr %v{k}f{i}p\n  call void %visit(ptr %v{k}f{i}, ptr @tarn.ti.{})",
                                i + 2,
                                mangle(fty.non_null())
                            );
                        }
                    }
                    trace.push(t);
                    let rel_all = self.variant_fields_code(sid, k, |_, _| true);
                    all.push(format!("{rel_all}  call void @tarn_cyclic_free(ptr %p, ptr @tarn.ti.{m})\n"));
                    let rel_acyclic = self.variant_fields_code(sid, k, |c, t| !c.is_cyclic(t));
                    acyclic.push(format!("{rel_acyclic}  call void @tarn.mem.{m}(ptr %p)\n"));
                    mem.push(self.variant_free_code(sid, k));
                }
                let _ = writeln!(out, "define internal void @tarn.trace.{m}(ptr %p, ptr %visit) #0 {{\n{}}}\n", variant_switch(&trace));
                let _ = writeln!(out, "define internal void @tarn.drop.{m}(ptr %p) #0 {{\n{}}}\n", variant_switch(&all));
                let _ = writeln!(out, "define internal void @tarn.white.{m}(ptr %p) #0 {{\n{}}}\n", variant_switch(&acyclic));
                let _ = writeln!(out, "define internal void @tarn.mem.{m}(ptr %p) #0 {{\n{}}}\n", variant_switch(&mem));
            }
            Type::Map(..) => self.map_rc_functions(t, true, out),
            _ => unreachable!("only structs, enums, lists and maps can be cyclic"),
        }
    }

    /// Code (in a function with the value in `%p`) releasing the reference
    /// fields of variant `k` of enum `sid` for which `keep(self, type)` holds.
    fn variant_fields_code(&mut self, sid: StructId, k: usize, keep: impl Fn(&mut Self, &Type) -> bool) -> String {
        let lt = self.variant_llty(sid, k);
        let fields: Vec<Type> = self.prog.structs[sid].variants()[k].fields.iter().map(|f| f.ty.clone()).collect();
        let mut out = String::new();
        for (i, fty) in fields.iter().enumerate() {
            if !is_ref(fty) || !keep(self, fty) {
                continue;
            }
            let rel = self.release_fn(fty);
            let _ = writeln!(out, "  %v{k}f{i}p = getelementptr inbounds {lt}, ptr %p, i32 0, i32 {}", i + 2);
            let _ = writeln!(out, "  %v{k}f{i} = load ptr, ptr %v{k}f{i}p");
            let _ = writeln!(out, "  call void {rel}(ptr %v{k}f{i})");
        }
        out
    }

    /// Code freeing `%p`, a value of variant `k` of enum `sid`.
    fn variant_free_code(&self, sid: StructId, k: usize) -> String {
        let lt = self.variant_llty(sid, k);
        format!("  %v{k}szp = getelementptr {lt}, ptr null, i32 1\n  %v{k}sz = ptrtoint ptr %v{k}szp to i64\n  call void @tarn_free(ptr %p, i64 %v{k}sz)\n")
    }

    fn rc_functions(&mut self) -> String {
        let mut out = String::new();
        let md = self.tbaa("rc");
        let mut i = self.rc_done;
        while i < self.rc_types.len() {
            let t = self.rc_types[i].clone();
            i += 1;
            if let Type::Nullable(inner) = &t {
                // Releasing a nullable reference: skip null, then release as usual.
                let rel = self.release_fn(inner);
                let _ = writeln!(
                    out,
                    "define internal void @tarn.release.{}(ptr %p) #2 {{\n  %z = icmp eq ptr %p, null\n  br i1 %z, label %done, label %rel\nrel:\n  call void {rel}(ptr %p)\n  br label %done\ndone:\n  ret void\n}}\n",
                    mangle(&t)
                );
                continue;
            }
            if t == Type::Handle {
                let _ = writeln!(
                    out,
                    "define internal void @tarn.release.handle(ptr %p) #2 {{\n  %old = atomicrmw sub ptr %p, i64 1 acq_rel\n  %z = icmp eq i64 %old, 1\n  br i1 %z, label %free, label %done\nfree:\n  call void @tarn_handle_free(ptr %p)\n  br label %done\ndone:\n  ret void\n}}\n"
                );
                continue;
            }
            // Function and interface values are released through their own type info.
            if let Type::Func(..) | Type::Iface(_) = t {
                self.func_rc_functions(&t, &mut out);
                continue;
            }
            if self.is_cyclic(&t) {
                self.cyclic_functions(&t, &mut out);
                continue;
            }
            let m = mangle(&t);
            let drop = self.drop_fn(&t);
            let _ = writeln!(
                out,
                "define internal void @tarn.release.{m}(ptr %p) #2 {{\n  %rc = load i64, ptr %p{md}\n  %n = sub i64 %rc, 1\n  store i64 %n, ptr %p{md}\n  %z = icmp eq i64 %n, 0\n  br i1 %z, label %free, label %done\nfree:\n  call void @tarn_drop_slow(ptr %p, ptr {drop})\n  br label %done\ndone:\n  ret void\n}}\n"
            );
            match &t {
                Type::Struct(sid) => {
                    let s = &self.prog.structs[*sid];
                    let sname = self.type_names[*sid].clone();
                    let fields: Vec<(usize, Type)> = s.fields.iter().enumerate().filter(|(_, f)| is_ref(&f.ty)).map(|(i, f)| (i, f.ty.clone())).collect();
                    let mut body = String::new();
                    for (k, (idx, fty)) in fields.iter().enumerate() {
                        let rel = self.release_fn(fty);
                        let _ = writeln!(body, "  %f{k}p = getelementptr inbounds %struct.{sname}, ptr %p, i32 0, i32 {}", idx + 1);
                        let _ = writeln!(body, "  %f{k} = load ptr, ptr %f{k}p");
                        let _ = writeln!(body, "  call void {rel}(ptr %f{k})");
                    }
                    // `fields` releases what the struct points to (also used when its
                    // memory is reused); `drop` then frees the struct itself.
                    let _ = writeln!(out, "define internal void @tarn.fields.{m}(ptr %p) #0 {{\n{body}  ret void\n}}\n");
                    // `fn drop(self)` runs first, on the value brought back to one
                    // reference; if it kept another one somewhere, that's a bug.
                    let user_drop = match s.drop {
                        Some(fid) => format!(
                            "  store i64 1, ptr %p\n  call void @{}(ptr %p)\n  %rc = load i64, ptr %p\n  %is.kept = icmp ne i64 %rc, 1\n  br i1 %is.kept, label %kept, label %free\nkept:\n  call void @tarn_drop_kept()\n  unreachable\nfree:\n",
                            self.prog.funcs[fid].symbol
                        ),
                        None => String::new(),
                    };
                    let _ = writeln!(
                        out,
                        "define internal void @tarn.drop.{m}(ptr %p) #0 {{\n{user_drop}  call void @tarn.fields.{m}(ptr %p)\n  %szp = getelementptr %struct.{sname}, ptr null, i32 1\n  %sz = ptrtoint ptr %szp to i64\n  call void @tarn_free(ptr %p, i64 %sz)\n  ret void\n}}\n"
                    );
                }
                Type::Enum(sid, true) => {
                    let sid = *sid;
                    let n = self.prog.structs[sid].variants().len();
                    let mut release = Vec::new();
                    let mut free = Vec::new();
                    for k in 0..n {
                        release.push(self.variant_fields_code(sid, k, |_, _| true));
                        free.push(self.variant_free_code(sid, k));
                    }
                    // `fields` releases what the value holds (also used when its memory
                    // is reused); `drop` also frees it, with its variant's size.
                    let fields_body = variant_switch(&release);
                    let drop_body = variant_switch(&release.iter().zip(&free).map(|(a, b)| format!("{a}{b}")).collect::<Vec<_>>());
                    let _ = writeln!(out, "define internal void @tarn.fields.{m}(ptr %p) #0 {{\n{fields_body}}}\n");
                    let _ = writeln!(out, "define internal void @tarn.drop.{m}(ptr %p) #0 {{\n{drop_body}}}\n");
                }
                Type::List(e) if is_ref(e) => {
                    let rel = self.release_fn(e);
                    let _ = writeln!(
                        out,
                        "define internal void @tarn.drop.{m}(ptr %p) #0 {{\nentry:\n  %lenp = getelementptr inbounds %TarnList, ptr %p, i32 0, i32 1\n  %len = load i64, ptr %lenp\n  %dp = getelementptr inbounds %TarnList, ptr %p, i32 0, i32 3\n  %data = load ptr, ptr %dp\n  br label %cond\ncond:\n  %i = phi i64 [ 0, %entry ], [ %i1, %body ]\n  %c = icmp slt i64 %i, %len\n  br i1 %c, label %body, label %done\nbody:\n  %ep = getelementptr inbounds ptr, ptr %data, i64 %i\n  %e = load ptr, ptr %ep\n  call void {rel}(ptr %e)\n  %i1 = add i64 %i, 1\n  br label %cond\ndone:\n  call void @tarn_list_free(ptr %p)\n  ret void\n}}\n"
                    );
                }
                Type::Map(..) => self.map_rc_functions(&t, false, &mut out),
                _ => {}
            }
        }
        self.rc_done = i;
        out
    }

    fn checked_int(&mut self, intrinsic: &str, a: &str, b: &str, span: Span) -> String {
        let r = self.fresh();
        self.emit(format!("{r} = call {{ i64, i1 }} @llvm.{intrinsic}.with.overflow.i64(i64 {a}, i64 {b})"));
        let v = self.fresh();
        self.emit(format!("{v} = extractvalue {{ i64, i1 }} {r}, 0"));
        let o = self.fresh();
        self.emit(format!("{o} = extractvalue {{ i64, i1 }} {r}, 1"));
        let loc = self.loc(span);
        self.panic_if(&o, format!("call void @tarn_panic_overflow({loc})"));
        v
    }

    /// `<=>` from two `i1` results: `(a > b) - (a < b)`.
    fn three_way(&mut self, gt: &str, lt: &str) -> String {
        let g = self.fresh();
        self.emit(format!("{g} = zext i1 {gt} to i64"));
        let l = self.fresh();
        self.emit(format!("{l} = zext i1 {lt} to i64"));
        let r = self.fresh();
        self.emit(format!("{r} = sub i64 {g}, {l}"));
        r
    }

    /// Apply a (non-short-circuit) binary operator to already-evaluated operands.
    fn binop_values(&mut self, op: BinOp, ty: &Type, a: &str, b: &str, span: Span) -> String {
        if op == BinOp::Cmp {
            let (gt, lt) = (self.fresh(), self.fresh());
            match ty {
                Type::Int => {
                    self.emit(format!("{gt} = icmp sgt i64 {a}, {b}"));
                    self.emit(format!("{lt} = icmp slt i64 {a}, {b}"));
                }
                Type::Float => {
                    self.emit(format!("{gt} = fcmp ogt double {a}, {b}"));
                    self.emit(format!("{lt} = fcmp olt double {a}, {b}"));
                }
                Type::Str => {
                    let c = self.fresh();
                    self.emit(format!("{c} = call i64 @tarn_str_cmp(ptr {a}, ptr {b})"));
                    self.emit(format!("{gt} = icmp sgt i64 {c}, 0"));
                    self.emit(format!("{lt} = icmp slt i64 {c}, 0"));
                }
                _ => unreachable!("<=> on {ty:?}"),
            }
            return self.three_way(&gt, &lt);
        }
        let r = self.fresh();
        match ty {
            Type::Int => match op {
                BinOp::Add => return self.checked_int("sadd", a, b, span),
                BinOp::Sub => return self.checked_int("ssub", a, b, span),
                BinOp::Mul => return self.checked_int("smul", a, b, span),
                BinOp::Div | BinOp::Mod => {
                    let loc = self.loc(span);
                    let z = self.fresh();
                    self.emit(format!("{z} = icmp eq i64 {b}, 0"));
                    self.panic_if(&z, format!("call void @tarn_panic_divzero({loc})"));
                    let m1 = self.fresh();
                    self.emit(format!("{m1} = icmp eq i64 {a}, {}", i64::MIN));
                    let m2 = self.fresh();
                    self.emit(format!("{m2} = icmp eq i64 {b}, -1"));
                    let both = self.fresh();
                    self.emit(format!("{both} = and i1 {m1}, {m2}"));
                    self.panic_if(&both, format!("call void @tarn_panic_overflow({loc})"));
                    let inst = if op == BinOp::Div { "sdiv" } else { "srem" };
                    self.emit(format!("{r} = {inst} i64 {a}, {b}"));
                }
                _ => {
                    let cc = match op {
                        BinOp::Eq => "eq",
                        BinOp::Ne => "ne",
                        BinOp::Lt => "slt",
                        BinOp::Le => "sle",
                        BinOp::Gt => "sgt",
                        BinOp::Ge => "sge",
                        _ => unreachable!(),
                    };
                    self.emit(format!("{r} = icmp {cc} i64 {a}, {b}"));
                }
            },
            Type::Float => {
                let inst = match op {
                    BinOp::Add => "fadd double",
                    BinOp::Sub => "fsub double",
                    BinOp::Mul => "fmul double",
                    BinOp::Div => "fdiv double",
                    BinOp::Mod => "frem double",
                    BinOp::Eq => "fcmp oeq double",
                    BinOp::Ne => "fcmp une double",
                    BinOp::Lt => "fcmp olt double",
                    BinOp::Le => "fcmp ole double",
                    BinOp::Gt => "fcmp ogt double",
                    BinOp::Ge => "fcmp oge double",
                    _ => unreachable!(),
                };
                self.emit(format!("{r} = {inst} {a}, {b}"));
            }
            Type::Bool => {
                let cc = if op == BinOp::Eq { "eq" } else { "ne" };
                self.emit(format!("{r} = icmp {cc} i1 {a}, {b}"));
            }
            Type::Enum(_, false) => {
                let cc = if op == BinOp::Eq { "eq" } else { "ne" };
                self.emit(format!("{r} = icmp {cc} i64 {a}, {b}"));
            }
            Type::Str | Type::Bytes => match op {
                BinOp::Add => self.emit(format!("{r} = call ptr @tarn_str_concat(ptr {a}, ptr {b})")),
                BinOp::Eq | BinOp::Ne => {
                    let eq = self.fresh();
                    self.emit(format!("{eq} = call i64 @tarn_str_eq(ptr {a}, ptr {b})"));
                    let cc = if op == BinOp::Eq { "ne" } else { "eq" };
                    self.emit(format!("{r} = icmp {cc} i64 {eq}, 0"));
                }
                _ => {
                    let c = self.fresh();
                    self.emit(format!("{c} = call i64 @tarn_str_cmp(ptr {a}, ptr {b})"));
                    let cc = match op {
                        BinOp::Lt => "slt",
                        BinOp::Le => "sle",
                        BinOp::Gt => "sgt",
                        BinOp::Ge => "sge",
                        _ => unreachable!(),
                    };
                    self.emit(format!("{r} = icmp {cc} i64 {c}, 0"));
                }
            },
            _ => unreachable!("binary op on {ty:?}"),
        }
        r
    }

    fn emit_to_string(&mut self, ty: &Type, v: &str) -> String {
        let r = self.fresh();
        match ty {
            Type::Str => return v.to_string(),
            Type::Int => self.emit(format!("{r} = call ptr @tarn_int_to_str(i64 {v})")),
            Type::Float => self.emit(format!("{r} = call ptr @tarn_float_to_str(double {v})")),
            Type::Bool => {
                let z = self.fresh();
                self.emit(format!("{z} = zext i1 {v} to i64"));
                self.emit(format!("{r} = call ptr @tarn_bool_to_str(i64 {z})"));
            }
            // The variant's name (an immortal string literal).
            Type::Enum(sid, false) => {
                let n = self.prog.structs[*sid].variants().len();
                let table = self.name_table(*sid);
                let ep = self.fresh();
                self.emit(format!("{ep} = getelementptr inbounds [{n} x ptr], ptr {table}, i64 0, i64 {v}"));
                self.emit(format!("{r} = load ptr, ptr {ep}"));
            }
            _ => unreachable!(),
        }
        r
    }

    /// Evaluate an rvalue; returns the LLVM value (empty for unit).
    fn rvalue(&mut self, r: &Rvalue) -> String {
        match r {
            Rvalue::Use(o) => self.operand(o),
            Rvalue::Binary(op, ty, a, b, span) => {
                let a = self.operand(a);
                let b = self.operand(b);
                self.binop_values(*op, ty, &a, &b, *span)
            }
            Rvalue::Neg(ty, x, span) => {
                let v = self.operand(x);
                if *ty == Type::Int {
                    self.checked_int("ssub", "0", &v, *span)
                } else {
                    let r = self.fresh();
                    self.emit(format!("{r} = fneg double {v}"));
                    r
                }
            }
            Rvalue::Not(x) => {
                let v = self.operand(x);
                let r = self.fresh();
                self.emit(format!("{r} = xor i1 {v}, true"));
                r
            }
            Rvalue::Call(fid, args, span) => {
                let mut vals = Vec::new();
                for a in args {
                    let ty = llty(&self.f.operand_ty(a));
                    let v = self.operand(a);
                    vals.push(format!("{ty} {v}"));
                }
                let callee = &self.prog.funcs[*fid];
                if callee.track_caller {
                    vals.push(self.loc(*span));
                }
                let sym = callee.symbol.clone();
                if callee.ret == Type::Unit {
                    self.emit(format!("call void @{sym}({})", vals.join(", ")));
                    String::new()
                } else {
                    let rt = llty(&callee.ret);
                    let r = self.fresh();
                    self.emit(format!("{r} = call {rt} @{sym}({})", vals.join(", ")));
                    r
                }
            }
            Rvalue::Builtin(b, args, span) => self.builtin(*b, args, *span),
            Rvalue::Closure(func, sid, args) => self.closure_value(*func, *sid, args),
            Rvalue::CallIndirect(f, args, _) => self.call_indirect(f, args),
            Rvalue::Boxed(sid, o) => self.box_value(*sid, o),
            Rvalue::CallMethod(recv, slot, args, ret, _) => self.call_method(recv, *slot, args, ret),
            Rvalue::Field(obj, sid, idx) => {
                let o = self.operand(&Operand::Var(*obj));
                let s = &self.prog.structs[*sid];
                let sname = self.type_names[*sid].clone();
                let ft = llty(&s.fields[*idx].ty);
                let p = self.fresh();
                let slot = self.field_slot(*sid, *idx);
                self.emit(format!("{p} = getelementptr inbounds %struct.{sname}, ptr {o}, i32 0, i32 {slot}"));
                let r = self.fresh();
                let md = self.field_tbaa(*sid, *idx);
                self.emit(format!("{r} = load {ft}, ptr {p}{md}"));
                r
            }
            Rvalue::Index(list, index, span) => {
                let elem = list_elem(&self.f.vars[*list].ty);
                let l = self.operand(&Operand::Var(*list));
                let i = self.operand(index);
                let p = self.list_elem_ptr(&l, &i, &elem, *span);
                let r = self.fresh();
                let md = self.elem_tbaa(&elem);
                self.emit(format!("{r} = load {}, ptr {p}{md}", llty(&elem)));
                r
            }
            Rvalue::New(Ctor::Variant(sid, k), args) if !self.boxed(*sid) => {
                debug_assert!(args.is_empty());
                k.to_string()
            }
            Rvalue::New(Ctor::Variant(sid, k), args) if args.is_empty() => self.unit_value(*sid, *k),
            Rvalue::New(c, args) | Rvalue::Reuse(_, c, args) => {
                let vals: Vec<(String, Type)> = args.iter().map(|a| (self.operand(a), self.f.operand_ty(a))).collect();
                // LLVM type, its type in Tarn, and the index of the first field.
                let (lt, ty, first) = match *c {
                    Ctor::Struct(sid) => (format!("%struct.{}", self.type_names[sid]), Type::Struct(sid), 1),
                    Ctor::Variant(sid, k) => (self.variant_llty(sid, k), Type::Enum(sid, true), 2),
                };
                let szp = self.fresh();
                self.emit(format!("{szp} = getelementptr {lt}, ptr null, i32 1"));
                let sz = self.fresh();
                self.emit(format!("{sz} = ptrtoint ptr {szp} to i64"));
                let p = self.fresh();
                if let Rvalue::Reuse(tok, ..) = r {
                    // Build in the reused memory when there is some.
                    let t = self.operand(&Operand::Var(*tok));
                    let none = self.fresh();
                    self.emit(format!("{none} = icmp eq ptr {t}, null"));
                    let from = self.cur_label.clone();
                    let la = self.new_label("reuse.alloc");
                    let ld = self.new_label("reuse.have");
                    self.emit_term(format!("br i1 {none}, label %{la}, label %{ld}"));
                    self.start_block(&la);
                    let m = self.fresh();
                    self.emit(format!("{m} = call ptr @tarn_alloc(i64 {sz})"));
                    self.br(&ld);
                    self.start_block(&ld);
                    self.emit(format!("{p} = phi ptr [ {m}, %{la} ], [ {t}, %{from} ]"));
                } else {
                    self.emit(format!("{p} = call ptr @tarn_alloc(i64 {sz})"));
                }
                let md = self.tbaa("rc");
                let one = if self.is_cyclic(&ty) { 8 } else { 1 };
                self.emit(format!("store i64 {one}, ptr {p}{md}"));
                if let Ctor::Variant(_, k) = c {
                    let tp = self.fresh();
                    self.emit(format!("{tp} = getelementptr inbounds i8, ptr {p}, i64 8"));
                    let md = self.tbaa("enum.tag");
                    self.emit(format!("store i64 {k}, ptr {tp}{md}"));
                }
                for (i, (v, vty)) in vals.iter().enumerate() {
                    let fp = self.fresh();
                    self.emit(format!("{fp} = getelementptr inbounds {lt}, ptr {p}, i32 0, i32 {}", i + first));
                    let md = match *c {
                        Ctor::Struct(sid) => self.field_tbaa(sid, i),
                        Ctor::Variant(sid, k) => self.variant_tbaa(sid, k, i),
                    };
                    self.emit(format!("store {} {v}, ptr {fp}{md}", llty(vty)));
                }
                p
            }
            Rvalue::IsType(v, t) => {
                let val = self.operand(&Operand::Var(*v));
                let finder = self.box_finder(t);
                let b = self.fresh();
                self.emit(format!("{b} = call ptr {finder}(ptr {val})"));
                let r = self.fresh();
                self.emit(format!("{r} = icmp ne ptr {b}, null"));
                r
            }
            Rvalue::Unbox(v, t) => {
                let val = self.operand(&Operand::Var(*v));
                let finder = self.box_finder(t);
                let b = self.fresh();
                self.emit(format!("{b} = call ptr {finder}(ptr {val})"));
                let vp = self.fresh();
                self.emit(format!("{vp} = getelementptr inbounds i8, ptr {b}, i64 24"));
                let r = self.fresh();
                self.emit(format!("{r} = load {}, ptr {vp}", llty(t)));
                r
            }
            Rvalue::Sync(op, types, args, span) => self.sync(*op, types, args, *span),
            Rvalue::Tag(v) => {
                let val = self.operand(&Operand::Var(*v));
                if matches!(self.f.vars[*v].ty, Type::Enum(_, false)) {
                    return val;
                }
                let tp = self.fresh();
                self.emit(format!("{tp} = getelementptr inbounds i8, ptr {val}, i64 8"));
                let r = self.fresh();
                let md = self.tbaa("enum.tag");
                self.emit(format!("{r} = load i64, ptr {tp}{md}"));
                r
            }
            Rvalue::VariantField(v, sid, k, i) => {
                let val = self.operand(&Operand::Var(*v));
                let lt = self.variant_llty(*sid, *k);
                let fty = llty(&self.prog.structs[*sid].variants()[*k].fields[*i].ty);
                let fp = self.fresh();
                self.emit(format!("{fp} = getelementptr inbounds {lt}, ptr {val}, i32 0, i32 {}", i + 2));
                let r = self.fresh();
                let md = self.variant_tbaa(*sid, *k, *i);
                self.emit(format!("{r} = load {fty}, ptr {fp}{md}"));
                r
            }
            Rvalue::MapNew(t, n) => {
                let ti = self.map_ti(t);
                let m = self.fresh();
                self.emit(format!("{m} = call ptr @tarn_map_new(ptr {ti}, i64 {n})"));
                if self.is_cyclic(t) {
                    let md = self.tbaa("rc");
                    self.emit(format!("store i64 8, ptr {m}{md}"));
                }
                m
            }
            Rvalue::ListNew(elem, args) => {
                let sz = elem_size(elem);
                let l = self.fresh();
                self.emit(format!("{l} = call ptr @tarn_list_new(i64 {sz}, i64 {})", args.len()));
                if self.is_cyclic(&Type::List(Box::new(elem.clone()))) {
                    let md = self.tbaa("rc");
                    self.emit(format!("store i64 8, ptr {l}{md}"));
                }
                for a in args {
                    let v = self.operand(a);
                    let slot = self.push_slot(&l, elem);
                    let md = self.elem_tbaa(elem);
                    self.emit(format!("store {} {v}, ptr {slot}{md}", llty(elem)));
                }
                l
            }
        }
    }

    fn builtin(&mut self, b: Builtin, args: &[Operand], span: Span) -> String {
        let tys: Vec<Type> = args.iter().map(|a| self.f.operand_ty(a)).collect();
        let vals: Vec<String> = args.iter().map(|a| self.operand(a)).collect();
        let r = self.fresh();
        let loc = self.loc(span);
        match b {
            Builtin::Print => {
                let v = &vals[0];
                match &tys[0] {
                    Type::Int => self.emit(format!("call void @tarn_print_int(i64 {v})")),
                    Type::Float => self.emit(format!("call void @tarn_print_float(double {v})")),
                    Type::Str => self.emit(format!("call void @tarn_print_str(ptr {v})")),
                    Type::Bool => {
                        self.emit(format!("{r} = zext i1 {v} to i64"));
                        self.emit(format!("call void @tarn_print_bool(i64 {r})"));
                    }
                    _ => unreachable!(),
                }
                return String::new();
            }
            Builtin::Input => self.emit(format!("{r} = call ptr @tarn_input()")),
            Builtin::Args => self.emit(format!("{r} = call ptr @tarn_args()")),
            Builtin::Panic => {
                self.emit(format!("call void @tarn_panic_msg(ptr {}, {loc})", vals[0]));
                return String::new();
            }
            Builtin::Exit => {
                self.emit(format!("call void @tarn_exit(i64 {})", vals[0]));
                return String::new();
            }
            Builtin::Assert => {
                let failed = self.fresh();
                self.emit(format!("{failed} = xor i1 {}, true", vals[0]));
                self.panic_if(&failed, format!("call void @tarn_assert_fail({loc})"));
                return String::new();
            }
            Builtin::Sqrt => self.emit(format!("{r} = call double @llvm.sqrt.f64(double {})", vals[0])),
            Builtin::IntToFloat => self.emit(format!("{r} = sitofp i64 {} to double", vals[0])),
            Builtin::FloatToInt => self.emit(format!("{r} = call i64 @llvm.fptosi.sat.i64.f64(double {})", vals[0])),
            Builtin::StrToInt => self.emit(format!("{r} = call i64 @tarn_str_to_int(ptr {}, {loc})", vals[0])),
            Builtin::StrToFloat => self.emit(format!("{r} = call double @tarn_str_to_float(ptr {}, {loc})", vals[0])),
            Builtin::Rt(i) => {
                let (name, params, ret, takes_loc) = crate::stdlib::RT[i as usize];
                let mut args = Vec::new();
                for (p, v) in params.iter().zip(&vals) {
                    if crate::stdlib::parse_type(p) == Type::Bool {
                        let w = self.fresh();
                        self.emit(format!("{w} = zext i1 {v} to i64"));
                        args.push(format!("i64 {w}"));
                    } else {
                        args.push(format!("{} {v}", rt_llty(p)));
                    }
                }
                if takes_loc {
                    args.push(loc.clone());
                }
                let call = format!("@tarn_rt_{name}({})", args.join(", "));
                match crate::stdlib::parse_type(ret) {
                    Type::Unit => {
                        self.emit(format!("call void {call}"));
                        return String::new();
                    }
                    Type::Bool => {
                        let w = self.fresh();
                        self.emit(format!("{w} = call i64 {call}"));
                        self.emit(format!("{r} = icmp ne i64 {w}, 0"));
                    }
                    _ => self.emit(format!("{r} = call {} {call}", rt_llty(ret))),
                }
            }
            Builtin::StrChars => self.emit(format!("{r} = call ptr @tarn_str_chars(ptr {})", vals[0])),
            Builtin::StrCharAt => self.emit(format!("{r} = call ptr @tarn_str_char_at(ptr {}, i64 {})", vals[0], vals[1])),
            Builtin::StrCharCount => self.emit(format!("{r} = call i64 @tarn_str_char_count(ptr {})", vals[0])),
            Builtin::StrSubstring => {
                self.emit(format!("{r} = call ptr @tarn_str_substring(ptr {}, i64 {}, i64 {}, {loc})", vals[0], vals[1], vals[2]))
            }
            Builtin::StrContains | Builtin::StrStartsWith | Builtin::StrEndsWith => {
                let f = match b {
                    Builtin::StrContains => "tarn_str_contains",
                    Builtin::StrStartsWith => "tarn_str_starts_with",
                    _ => "tarn_str_ends_with",
                };
                let raw = self.fresh();
                self.emit(format!("{raw} = call i64 @{f}(ptr {}, ptr {})", vals[0], vals[1]));
                self.emit(format!("{r} = icmp ne i64 {raw}, 0"));
            }
            Builtin::RealtimeNs => self.emit(format!("{r} = call i64 @tarn_time_realtime_ns()")),
            Builtin::MonotonicNs => self.emit(format!("{r} = call i64 @tarn_time_monotonic_ns()")),
            Builtin::SleepNs => {
                self.emit(format!("call void @tarn_time_sleep_ns(i64 {})", vals[0]));
                return String::new();
            }
            Builtin::ToStr => return self.emit_to_string(&tys[0], &vals[0]),
            Builtin::StrLen => {
                let lp = self.fresh();
                self.emit(format!("{lp} = getelementptr inbounds i8, ptr {}, i64 8", vals[0]));
                let md = self.tbaa("str.len");
                self.emit(format!("{r} = load i64, ptr {lp}{md}"));
            }
            Builtin::ListLen => return self.list_len(&vals[0]),
            Builtin::StrAppendOwned => self.emit(format!("{r} = call ptr @tarn_str_append_owned(ptr {}, ptr {})", vals[0], vals[1])),
            Builtin::ListPush => {
                let elem = list_elem(&tys[0]);
                let slot = self.push_slot(&vals[0], &elem);
                let md = self.elem_tbaa(&elem);
                self.emit(format!("store {} {}, ptr {slot}{md}", llty(&elem), vals[1]));
                return String::new();
            }
            Builtin::ListPop => {
                let elem = list_elem(&tys[0]);
                let sz = elem_size(&elem);
                let slot = self.fresh();
                self.emit(format!("{slot} = call ptr @tarn_list_pop_slot(ptr {}, i64 {sz}, {loc})", vals[0]));
                let md = self.elem_tbaa(&elem);
                self.emit(format!("{r} = load {}, ptr {slot}{md}", llty(&elem)));
            }
            Builtin::Inc => self.emit(format!("{r} = add nsw i64 {}, 1", vals[0])),
            Builtin::IsNull => {
                if is_pair(&tys[0]) {
                    let has = self.fresh();
                    self.emit(format!("{has} = extractvalue {} {}, 0", llty(&tys[0]), vals[0]));
                    self.emit(format!("{r} = xor i1 {has}, true"));
                } else {
                    self.emit(format!("{r} = icmp eq ptr {}, null", vals[0]));
                }
            }
            Builtin::Wrap => {
                let pair = llty(&tys[0].clone().nullable());
                let inner = llty(&tys[0]);
                let zero = match tys[0] {
                    Type::Float => "0.0",
                    Type::Bool => "false",
                    _ => "0",
                };
                self.emit(format!("{r} = insertvalue {pair} {{ i1 true, {inner} {zero} }}, {inner} {}, 1", vals[0]));
            }
            Builtin::Unwrap => self.emit(format!("{r} = extractvalue {} {}, 1", llty(&tys[0]), vals[0])),
            Builtin::StrToBoolOrNull => {
                let code = self.fresh();
                self.emit(format!("{code} = call i64 @tarn_str_parse_bool(ptr {})", vals[0]));
                let has = self.fresh();
                self.emit(format!("{has} = icmp sge i64 {code}, 0"));
                let v = self.fresh();
                self.emit(format!("{v} = icmp eq i64 {code}, 1"));
                let half = self.fresh();
                self.emit(format!("{half} = insertvalue {{ i1, i1 }} undef, i1 {has}, 0"));
                self.emit(format!("{r} = insertvalue {{ i1, i1 }} {half}, i1 {v}, 1"));
            }
            Builtin::StrToIntOrNull | Builtin::StrToFloatOrNull => {
                let (f, t) = if b == Builtin::StrToIntOrNull { ("tarn_str_parse_int", "i64") } else { ("tarn_str_parse_float", "double") };
                let slot = format!("%parse{}", self.tmp);
                let _ = writeln!(self.allocas, "  {slot} = alloca {t}");
                let ok = self.fresh();
                self.emit(format!("{ok} = call i64 @{f}(ptr {}, ptr {slot})", vals[0]));
                let has = self.fresh();
                self.emit(format!("{has} = icmp ne i64 {ok}, 0"));
                let v = self.fresh();
                self.emit(format!("{v} = load {t}, ptr {slot}"));
                let half = self.fresh();
                self.emit(format!("{half} = insertvalue {{ i1, {t} }} undef, i1 {has}, 0"));
                self.emit(format!("{r} = insertvalue {{ i1, {t} }} {half}, {t} {v}, 1"));
            }
            _ => return self.extra_builtin(b, &vals, &tys, span),
        }
        r
    }
}
