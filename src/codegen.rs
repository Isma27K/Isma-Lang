fn llty(t: &Type) -> &'static str {
    match t {
        Type::Int => "i64",
        Type::Float => "double",
        Type::Bool => "i1",
        Type::Str | Type::List(_) | Type::Struct(_) => "ptr",
        Type::Unit => "void",
        Type::Error => unreachable!("error type reached codegen"),
    }
}

/// Size in bytes of a list element of this type.
fn elem_size(t: &Type) -> u64 {
    match t {
        Type::Bool => 1,
        _ => 8,
    }
}

fn list_elem(t: &Type) -> Type {
    match t {
        Type::List(e) => (**e).clone(),
        _ => unreachable!("not a list: {t:?}"),
    }
}

/// A name for a reference-counted type, used in its release/drop functions.
fn mangle(t: &Type) -> String {
    match t {
        Type::Str => "str".into(),
        Type::List(e) => format!("list.{}", mangle(e)),
        Type::Struct(id) => format!("s{id}"),
        Type::Int => "int".into(),
        Type::Float => "float".into(),
        Type::Bool => "bool".into(),
        _ => unreachable!("no runtime representation: {t:?}"),
    }
}

/// The count every string literal starts with: so large it never reaches zero.
const RC_IMMORTAL: i64 = 1 << 62;

fn escape_bytes(b: &[u8]) -> String {
    let mut s = String::new();
    for &c in b {
        if (0x20..0x7f).contains(&c) && c != b'"' && c != b'\\' {
            s.push(c as char);
        } else {
            let _ = write!(s, "\\{c:02X}");
        }
    }
    s
}

fn float_const(v: f64) -> String {
    format!("0x{:016X}", v.to_bits())
}

struct Codegen<'a> {
    prog: &'a Program,
    sources: &'a SourceMap<'a>,
    /// The function being generated.
    f: &'a Func,
    /// Inside a `track_caller` function: the caller's location arguments.
    caller_loc: Option<String>,
    strings: HashMap<String, String>,
    globals: String,
    // per-function state
    body: String,
    allocas: String,
    tmp: usize,
    label: usize,
    cur_label: String,
    terminated: bool,
    /// TBAA alias classes, by name, in creation order.
    tbaa: Vec<String>,
    /// Types that need release/drop functions, in first-use order.
    rc_types: Vec<Type>,
    /// Memoized `cycles::is_cyclic`.
    cyclic: HashMap<Type, bool>,
}

impl<'a> Codegen<'a> {
    // ---------- emission helpers ----------

    fn fresh(&mut self) -> String {
        self.tmp += 1;
        format!("%t{}", self.tmp)
    }

    fn new_label(&mut self, hint: &str) -> String {
        self.label += 1;
        format!("{hint}{}", self.label)
    }

    /// Emit an instruction. If the current block already ended (e.g. after a
    /// `return`), the instruction goes into a fresh unreachable block.
    fn emit(&mut self, s: impl AsRef<str>) {
        if self.terminated {
            let l = self.new_label("dead");
            let _ = writeln!(self.body, "{l}:");
            self.cur_label = l;
            self.terminated = false;
        }
        self.body.push_str("  ");
        self.body.push_str(s.as_ref());
        self.body.push('\n');
    }

    fn emit_term(&mut self, s: impl AsRef<str>) {
        self.emit(s);
        self.terminated = true;
    }

    fn br(&mut self, label: &str) {
        if !self.terminated {
            self.emit_term(format!("br label %{label}"));
        }
    }

    fn start_block(&mut self, label: &str) {
        self.br(label);
        let _ = writeln!(self.body, "{label}:");
        self.cur_label = label.to_string();
        self.terminated = false;
    }

    /// `, !tbaa !N` suffix for a memory access of the given alias class.
    fn tbaa(&mut self, class: &str) -> String {
        let i = match self.tbaa.iter().position(|c| c == class) {
            Some(i) => i,
            None => {
                self.tbaa.push(class.to_string());
                self.tbaa.len() - 1
            }
        };
        format!(", !tbaa !{}", 2 * i + 2)
    }

    fn elem_tbaa(&mut self, elem: &Type) -> String {
        let class = format!("list.elem.{}", llty(elem));
        self.tbaa(&class)
    }

    fn field_tbaa(&mut self, sid: StructId, idx: usize) -> String {
        let class = format!("field.{}.{idx}", self.prog.structs[sid].name);
        self.tbaa(&class)
    }

    /// `ptr file, i32 line, i32 col` arguments for runtime panics.
    fn loc(&self, span: Span) -> String {
        if let Some(caller) = &self.caller_loc {
            return caller.clone();
        }
        let (file, line, col) = self.sources.locate(span.start);
        format!("ptr @.file.{file}, i32 {line}, i32 {col}")
    }

    /// Branch to a cold panic block when `cond` is true.
    fn panic_if(&mut self, cond: &str, panic_call: String) {
        let bad = self.new_label("panic");
        let ok = self.new_label("ok");
        self.emit_term(format!("br i1 {cond}, label %{bad}, label %{ok}"));
        self.start_block(&bad);
        self.emit(panic_call);
        self.emit_term("unreachable");
        self.start_block(&ok);
    }

    fn string_literal(&mut self, s: &str) -> String {
        if let Some(name) = self.strings.get(s) {
            return name.clone();
        }
        let name = format!("@.str.{}", self.strings.len());
        let b = s.as_bytes();
        let _ = writeln!(
            self.globals,
            "{name} = private unnamed_addr global {{ i64, i64, i64, [{n} x i8] }} {{ i64 {RC_IMMORTAL}, i64 {n}, i64 {n}, [{n} x i8] c\"{}\" }}, align 8",
            escape_bytes(b),
            n = b.len()
        );
        self.strings.insert(s.to_string(), name.clone());
        name
    }

    fn var_ty(&self, v: VarId) -> &'static str {
        llty(&self.f.vars[v].ty)
    }

    // ---------- functions ----------

    fn function(&mut self, f: &'a Func) -> String {
        self.f = f;
        self.body.clear();
        self.allocas.clear();
        self.tmp = 0;
        self.label = 0;
        self.cur_label = "entry".into();
        self.terminated = false;
        self.caller_loc = f.track_caller.then(|| "ptr %caller.file, i32 %caller.line, i32 %caller.col".to_string());

        for (id, v) in f.vars.iter().enumerate() {
            if v.ty != Type::Unit {
                let _ = writeln!(self.allocas, "  %v{id} = alloca {}", llty(&v.ty));
            }
        }
        let mut params = Vec::new();
        for (i, &id) in f.params.iter().enumerate() {
            let ty = self.var_ty(id);
            params.push(format!("{ty} %a{i}"));
            self.emit(format!("store {ty} %a{i}, ptr %v{id}"));
        }
        if f.track_caller {
            params.push("ptr %caller.file, i32 %caller.line, i32 %caller.col".to_string());
        }
        for (b, block) in f.blocks.iter().enumerate() {
            self.start_block(&format!("bb{b}"));
            for s in &block.stmts {
                self.stmt(s);
            }
            self.term(&block.term);
        }
        let linkage = if f.exported { "" } else { "internal " };
        format!(
            "; {}\ndefine {linkage}{} @{}({}) #0 {{\nentry:\n{}{}}}\n\n",
            f.name,
            llty(&f.ret),
            f.symbol,
            params.join(", "),
            self.allocas,
            self.body
        )
    }

    fn term(&mut self, t: &Term) {
        match t {
            Term::Goto(b) => self.emit_term(format!("br label %bb{b}")),
            Term::Branch(c, t, e) => {
                let c = self.operand(c);
                self.emit_term(format!("br i1 {c}, label %bb{t}, label %bb{e}"));
            }
            Term::Return(None) => self.emit_term("ret void"),
            Term::Return(Some(o)) => {
                let ty = llty(&self.f.operand_ty(o));
                let v = self.operand(o);
                self.emit_term(format!("ret {ty} {v}"));
            }
            Term::Unreachable => self.emit_term("unreachable"),
        }
    }

    // ---------- statements ----------

    fn stmt(&mut self, s: &Stmt) {
        match s {
            Stmt::Assign(v, r) => {
                let val = self.rvalue(r);
                let ty = self.var_ty(*v);
                self.emit(format!("store {ty} {val}, ptr %v{v}"));
            }
            Stmt::Eval(r) => {
                self.rvalue(r);
            }
            Stmt::Store { place, value, old } => {
                let v = self.operand(value);
                let (addr, ty, md) = match place {
                    Place::Field { obj, sid, idx } => {
                        let o = self.operand(&Operand::Var(*obj));
                        let p = self.fresh();
                        let sname = &self.prog.structs[*sid].name;
                        self.emit(format!("{p} = getelementptr inbounds %struct.{sname}, ptr {o}, i32 0, i32 {}", idx + 1));
                        let md = self.field_tbaa(*sid, *idx);
                        (p, self.prog.structs[*sid].fields[*idx].ty.clone(), md)
                    }
                    Place::Index { list, index, span } => {
                        let elem = list_elem(&self.f.vars[*list].ty);
                        let l = self.operand(&Operand::Var(*list));
                        let i = self.operand(index);
                        let p = self.list_elem_ptr(&l, &i, &elem, Some(*span));
                        let md = self.elem_tbaa(&elem);
                        (p, elem, md)
                    }
                };
                let lt = llty(&ty);
                if let Some(o) = old {
                    let cur = self.fresh();
                    self.emit(format!("{cur} = load {lt}, ptr {addr}{md}"));
                    self.emit(format!("store {lt} {cur}, ptr %v{o}"));
                }
                self.emit(format!("store {lt} {v}, ptr {addr}{md}"));
            }
            Stmt::Dup(v) => {
                let ty = self.f.vars[*v].ty.clone();
                let p = self.operand(&Operand::Var(*v));
                let md = self.tbaa("rc");
                let c = self.fresh();
                self.emit(format!("{c} = load i64, ptr {p}{md}"));
                let n = self.fresh();
                if self.is_cyclic(&ty) {
                    // Count in the upper bits; a new reference also marks it in use (black).
                    let m = self.fresh();
                    self.emit(format!("{m} = add i64 {c}, 8"));
                    self.emit(format!("{n} = and i64 {m}, -4"));
                } else {
                    self.emit(format!("{n} = add i64 {c}, 1"));
                }
                self.emit(format!("store i64 {n}, ptr {p}{md}"));
            }
            Stmt::Drop(v) => {
                let ty = self.f.vars[*v].ty.clone();
                let p = self.operand(&Operand::Var(*v));
                let rel = self.release_fn(&ty);
                self.emit(format!("call void {rel}(ptr {p})"));
            }
            Stmt::DropReuse(v, tok) => {
                // Last reference: release the fields and keep the memory as the
                // token. Otherwise just decrement, and the token is null.
                let ty = self.f.vars[*v].ty.clone();
                self.release_fn(&ty);
                let p = self.operand(&Operand::Var(*v));
                let md = self.tbaa("rc");
                let c = self.fresh();
                self.emit(format!("{c} = load i64, ptr {p}{md}"));
                let unique = self.fresh();
                self.emit(format!("{unique} = icmp eq i64 {c}, 1"));
                let lu = self.new_label("reuse.unique");
                let ls = self.new_label("reuse.shared");
                let ld = self.new_label("reuse.done");
                self.emit_term(format!("br i1 {unique}, label %{lu}, label %{ls}"));
                self.start_block(&lu);
                self.emit(format!("call void @isma.fields.{}(ptr {p})", mangle(&ty)));
                self.br(&ld);
                self.start_block(&ls);
                let n = self.fresh();
                self.emit(format!("{n} = sub i64 {c}, 1"));
                self.emit(format!("store i64 {n}, ptr {p}{md}"));
                self.br(&ld);
                self.start_block(&ld);
                let t = self.fresh();
                self.emit(format!("{t} = phi ptr [ {p}, %{lu} ], [ null, %{ls} ]"));
                self.emit(format!("store ptr {t}, ptr %v{tok}"));
            }
        }
    }

    // ---------- expressions ----------

    fn operand(&mut self, o: &Operand) -> String {
        match o {
            Operand::Var(v) => {
                let r = self.fresh();
                let ty = self.var_ty(*v);
                self.emit(format!("{r} = load {ty}, ptr %v{v}"));
                r
            }
            Operand::Int(v) => v.to_string(),
            Operand::Float(v) => float_const(*v),
            Operand::Bool(v) => v.to_string(),
            Operand::Str(s) => self.string_literal(s),
        }
    }

    /// Returns a pointer to element `i` of `list`, with a bounds check when `span` is given.
    fn list_elem_ptr(&mut self, list: &str, i: &str, elem: &Type, span: Option<Span>) -> String {
        if let Some(span) = span {
            let len = self.list_len(list);
            let oob = self.fresh();
            self.emit(format!("{oob} = icmp uge i64 {i}, {len}"));
            let loc = self.loc(span);
            self.panic_if(&oob, format!("call void @isma_panic_bounds(i64 {i}, i64 {len}, {loc})"));
        }
        let dp = self.fresh();
        self.emit(format!("{dp} = getelementptr inbounds %IsmaList, ptr {list}, i32 0, i32 3"));
        let data = self.fresh();
        let md_data = self.tbaa("list.data");
        self.emit(format!("{data} = load ptr, ptr {dp}{md_data}"));
        let ep = self.fresh();
        self.emit(format!("{ep} = getelementptr inbounds {}, ptr {data}, i64 {i}", llty(elem)));
        ep
    }

    /// Reserve a slot at the end of `list`. The common case (spare capacity)
    /// is inlined; only growth calls into the runtime.
    fn push_slot(&mut self, list: &str, elem: &Type) -> String {
        let sz = elem_size(elem);
        let md_len = self.tbaa("list.len");
        let md_cap = self.tbaa("list.cap");
        let md_data = self.tbaa("list.data");
        let lenp = self.fresh();
        self.emit(format!("{lenp} = getelementptr inbounds %IsmaList, ptr {list}, i32 0, i32 1"));
        let len = self.fresh();
        self.emit(format!("{len} = load i64, ptr {lenp}{md_len}"));
        let capp = self.fresh();
        self.emit(format!("{capp} = getelementptr inbounds %IsmaList, ptr {list}, i32 0, i32 2"));
        let cap = self.fresh();
        self.emit(format!("{cap} = load i64, ptr {capp}{md_cap}"));
        let full = self.fresh();
        self.emit(format!("{full} = icmp eq i64 {len}, {cap}"));
        let grow = self.new_label("push.grow");
        let fast = self.new_label("push.fast");
        let done = self.new_label("push.done");
        self.emit_term(format!("br i1 {full}, label %{grow}, label %{fast}"));
        self.start_block(&grow);
        let slow = self.fresh();
        self.emit(format!("{slow} = call ptr @isma_list_push_slot(ptr {list}, i64 {sz})"));
        self.br(&done);
        self.start_block(&fast);
        let dp = self.fresh();
        self.emit(format!("{dp} = getelementptr inbounds %IsmaList, ptr {list}, i32 0, i32 3"));
        let data = self.fresh();
        self.emit(format!("{data} = load ptr, ptr {dp}{md_data}"));
        let quick = self.fresh();
        self.emit(format!("{quick} = getelementptr inbounds {}, ptr {data}, i64 {len}", llty(elem)));
        let newlen = self.fresh();
        self.emit(format!("{newlen} = add nsw i64 {len}, 1"));
        self.emit(format!("store i64 {newlen}, ptr {lenp}{md_len}"));
        self.br(&done);
        self.start_block(&done);
        let slot = self.fresh();
        self.emit(format!("{slot} = phi ptr [ {slow}, %{grow} ], [ {quick}, %{fast} ]"));
        slot
    }

    fn list_len(&mut self, list: &str) -> String {
        let lp = self.fresh();
        self.emit(format!("{lp} = getelementptr inbounds %IsmaList, ptr {list}, i32 0, i32 1"));
        let len = self.fresh();
        let md = self.tbaa("list.len");
        self.emit(format!("{len} = load i64, ptr {lp}{md}"));
        len
    }

    /// The (always-inlined) function that drops one reference to a value of type `t`.
    fn release_fn(&mut self, t: &Type) -> String {
        if !self.rc_types.contains(t) {
            self.rc_types.push(t.clone());
        }
        format!("@isma.release.{}", mangle(t))
    }

    /// What frees a value of type `t` once its count reaches zero.
    fn drop_fn(&mut self, t: &Type) -> String {
        match t {
            Type::Str => "@isma_str_free".into(),
            Type::List(e) if !is_ref(e) => "@isma_list_free".into(),
            _ => format!("@isma.drop.{}", mangle(t)),
        }
    }

    /// Release and drop functions for every reference-counted type used.
    fn is_cyclic(&mut self, t: &Type) -> bool {
        if let Some(&c) = self.cyclic.get(t) {
            return c;
        }
        let c = crate::cycles::is_cyclic(t, &self.prog.structs);
        self.cyclic.insert(t.clone(), c);
        c
    }

    /// Release, trace and free functions plus the type info record for a type
    /// that can be part of a cycle (see `isma_collect_cycles` in the runtime).
    fn cyclic_functions(&mut self, t: &Type, out: &mut String) {
        let m = mangle(t);
        let _ = writeln!(
            out,
            "define internal void @isma.release.{m}(ptr %p) #2 {{\n  call void @isma_release_cyclic(ptr %p, ptr @isma.ti.{m})\n  ret void\n}}\n"
        );
        let _ = writeln!(
            out,
            "@isma.ti.{m} = internal constant {{ ptr, ptr, ptr, ptr }} {{ ptr @isma.trace.{m}, ptr @isma.drop.{m}, ptr @isma.white.{m}, ptr @isma.mem.{m} }}\n"
        );
        match t {
            Type::Struct(sid) => {
                let s = &self.prog.structs[*sid];
                let sname = s.name.clone();
                let fields: Vec<(usize, Type)> =
                    s.fields.iter().enumerate().filter(|(_, f)| is_ref(&f.ty)).map(|(i, f)| (i, f.ty.clone())).collect();
                let (mut trace, mut all, mut acyclic) = (String::new(), String::new(), String::new());
                for (k, (idx, fty)) in fields.iter().enumerate() {
                    let rel = self.release_fn(fty);
                    let load = format!(
                        "  %f{k}p = getelementptr inbounds %struct.{sname}, ptr %p, i32 0, i32 {}\n  %f{k} = load ptr, ptr %f{k}p\n",
                        idx + 1
                    );
                    let _ = writeln!(all, "{load}  call void {rel}(ptr %f{k})");
                    if self.is_cyclic(fty) {
                        let _ = writeln!(trace, "{load}  call void %visit(ptr %f{k}, ptr @isma.ti.{})", mangle(fty));
                    } else {
                        let _ = writeln!(acyclic, "{load}  call void {rel}(ptr %f{k})");
                    }
                }
                let _ = writeln!(out, "define internal void @isma.trace.{m}(ptr %p, ptr %visit) #0 {{\n{trace}  ret void\n}}\n");
                let _ = writeln!(
                    out,
                    "define internal void @isma.drop.{m}(ptr %p) #0 {{\n{all}  call void @isma_cyclic_free(ptr %p, ptr @isma.ti.{m})\n  ret void\n}}\n"
                );
                let _ = writeln!(out, "define internal void @isma.white.{m}(ptr %p) #0 {{\n{acyclic}  call void @isma.mem.{m}(ptr %p)\n  ret void\n}}\n");
                let _ = writeln!(
                    out,
                    "define internal void @isma.mem.{m}(ptr %p) #0 {{\n  %szp = getelementptr %struct.{sname}, ptr null, i32 1\n  %sz = ptrtoint ptr %szp to i64\n  call void @isma_free(ptr %p, i64 %sz)\n  ret void\n}}\n"
                );
            }
            Type::List(e) => {
                // A cyclic list's elements are themselves cyclic, so the collector
                // accounts for all of them: freeing a garbage list frees only memory.
                let rel = self.release_fn(e);
                let em = mangle(e);
                let each = |action: &str| {
                    format!(
                        "entry:\n  %lenp = getelementptr inbounds %IsmaList, ptr %p, i32 0, i32 1\n  %len = load i64, ptr %lenp\n  %dp = getelementptr inbounds %IsmaList, ptr %p, i32 0, i32 3\n  %data = load ptr, ptr %dp\n  br label %cond\ncond:\n  %i = phi i64 [ 0, %entry ], [ %i1, %body ]\n  %c = icmp slt i64 %i, %len\n  br i1 %c, label %body, label %done\nbody:\n  %ep = getelementptr inbounds ptr, ptr %data, i64 %i\n  %e = load ptr, ptr %ep\n  {action}\n  %i1 = add i64 %i, 1\n  br label %cond\ndone:\n"
                    )
                };
                let _ = writeln!(
                    out,
                    "define internal void @isma.trace.{m}(ptr %p, ptr %visit) #0 {{\n{}  ret void\n}}\n",
                    each(&format!("call void %visit(ptr %e, ptr @isma.ti.{em})"))
                );
                let _ = writeln!(
                    out,
                    "define internal void @isma.drop.{m}(ptr %p) #0 {{\n{}  call void @isma_cyclic_free(ptr %p, ptr @isma.ti.{m})\n  ret void\n}}\n",
                    each(&format!("call void {rel}(ptr %e)"))
                );
                let _ = writeln!(out, "define internal void @isma.white.{m}(ptr %p) #0 {{\n  call void @isma_list_free(ptr %p)\n  ret void\n}}\n");
                let _ = writeln!(out, "define internal void @isma.mem.{m}(ptr %p) #0 {{\n  call void @isma_list_free(ptr %p)\n  ret void\n}}\n");
            }
            _ => unreachable!("only structs and lists can be cyclic"),
        }
    }

    fn rc_functions(&mut self) -> String {
        let mut out = String::new();
        let md = self.tbaa("rc");
        let mut i = 0;
        while i < self.rc_types.len() {
            let t = self.rc_types[i].clone();
            i += 1;
            if self.is_cyclic(&t) {
                self.cyclic_functions(&t, &mut out);
                continue;
            }
            let m = mangle(&t);
            let drop = self.drop_fn(&t);
            let _ = writeln!(
                out,
                "define internal void @isma.release.{m}(ptr %p) #2 {{\n  %rc = load i64, ptr %p{md}\n  %n = sub i64 %rc, 1\n  store i64 %n, ptr %p{md}\n  %z = icmp eq i64 %n, 0\n  br i1 %z, label %free, label %done\nfree:\n  call void @isma_drop_slow(ptr %p, ptr {drop})\n  br label %done\ndone:\n  ret void\n}}\n"
            );
            match &t {
                Type::Struct(sid) => {
                    let s = &self.prog.structs[*sid];
                    let sname = s.name.clone();
                    let fields: Vec<(usize, Type)> = s.fields.iter().enumerate().filter(|(_, f)| is_ref(&f.ty)).map(|(i, f)| (i, f.ty.clone())).collect();
                    let mut body = String::new();
                    for (k, (idx, fty)) in fields.iter().enumerate() {
                        let rel = self.release_fn(fty);
                        let _ = writeln!(body, "  %f{k}p = getelementptr inbounds %struct.{sname}, ptr %p, i32 0, i32 {}", idx + 1);
                        let _ = writeln!(body, "  %f{k} = load ptr, ptr %f{k}p");
                        let _ = writeln!(body, "  call void {rel}(ptr %f{k})");
                    }
                    // `fields` releases what the struct points to (also used when its
                    // memory is reused); `drop` then frees the struct itself.
                    let _ = writeln!(out, "define internal void @isma.fields.{m}(ptr %p) #0 {{\n{body}  ret void\n}}\n");
                    let _ = writeln!(
                        out,
                        "define internal void @isma.drop.{m}(ptr %p) #0 {{\n  call void @isma.fields.{m}(ptr %p)\n  %szp = getelementptr %struct.{sname}, ptr null, i32 1\n  %sz = ptrtoint ptr %szp to i64\n  call void @isma_free(ptr %p, i64 %sz)\n  ret void\n}}\n"
                    );
                }
                Type::List(e) if is_ref(e) => {
                    let rel = self.release_fn(e);
                    let _ = writeln!(
                        out,
                        "define internal void @isma.drop.{m}(ptr %p) #0 {{\nentry:\n  %lenp = getelementptr inbounds %IsmaList, ptr %p, i32 0, i32 1\n  %len = load i64, ptr %lenp\n  %dp = getelementptr inbounds %IsmaList, ptr %p, i32 0, i32 3\n  %data = load ptr, ptr %dp\n  br label %cond\ncond:\n  %i = phi i64 [ 0, %entry ], [ %i1, %body ]\n  %c = icmp slt i64 %i, %len\n  br i1 %c, label %body, label %done\nbody:\n  %ep = getelementptr inbounds ptr, ptr %data, i64 %i\n  %e = load ptr, ptr %ep\n  call void {rel}(ptr %e)\n  %i1 = add i64 %i, 1\n  br label %cond\ndone:\n  call void @isma_list_free(ptr %p)\n  ret void\n}}\n"
                    );
                }
                _ => {}
            }
        }
        out
    }

    fn checked_int(&mut self, intrinsic: &str, a: &str, b: &str, span: Span) -> String {
        let r = self.fresh();
        self.emit(format!("{r} = call {{ i64, i1 }} @llvm.{intrinsic}.with.overflow.i64(i64 {a}, i64 {b})"));
        let v = self.fresh();
        self.emit(format!("{v} = extractvalue {{ i64, i1 }} {r}, 0"));
        let o = self.fresh();
        self.emit(format!("{o} = extractvalue {{ i64, i1 }} {r}, 1"));
        let loc = self.loc(span);
        self.panic_if(&o, format!("call void @isma_panic_overflow({loc})"));
        v
    }

    /// Apply a (non-short-circuit) binary operator to already-evaluated operands.
    fn binop_values(&mut self, op: BinOp, ty: &Type, a: &str, b: &str, span: Span) -> String {
        let r = self.fresh();
        match ty {
            Type::Int => match op {
                BinOp::Add => return self.checked_int("sadd", a, b, span),
                BinOp::Sub => return self.checked_int("ssub", a, b, span),
                BinOp::Mul => return self.checked_int("smul", a, b, span),
                BinOp::Div | BinOp::Mod => {
                    let loc = self.loc(span);
                    let z = self.fresh();
                    self.emit(format!("{z} = icmp eq i64 {b}, 0"));
                    self.panic_if(&z, format!("call void @isma_panic_divzero({loc})"));
                    let m1 = self.fresh();
                    self.emit(format!("{m1} = icmp eq i64 {a}, {}", i64::MIN));
                    let m2 = self.fresh();
                    self.emit(format!("{m2} = icmp eq i64 {b}, -1"));
                    let both = self.fresh();
                    self.emit(format!("{both} = and i1 {m1}, {m2}"));
                    self.panic_if(&both, format!("call void @isma_panic_overflow({loc})"));
                    let inst = if op == BinOp::Div { "sdiv" } else { "srem" };
                    self.emit(format!("{r} = {inst} i64 {a}, {b}"));
                }
                _ => {
                    let cc = match op {
                        BinOp::Eq => "eq",
                        BinOp::Ne => "ne",
                        BinOp::Lt => "slt",
                        BinOp::Le => "sle",
                        BinOp::Gt => "sgt",
                        BinOp::Ge => "sge",
                        _ => unreachable!(),
                    };
                    self.emit(format!("{r} = icmp {cc} i64 {a}, {b}"));
                }
            },
            Type::Float => {
                let inst = match op {
                    BinOp::Add => "fadd double",
                    BinOp::Sub => "fsub double",
                    BinOp::Mul => "fmul double",
                    BinOp::Div => "fdiv double",
                    BinOp::Mod => "frem double",
                    BinOp::Eq => "fcmp oeq double",
                    BinOp::Ne => "fcmp une double",
                    BinOp::Lt => "fcmp olt double",
                    BinOp::Le => "fcmp ole double",
                    BinOp::Gt => "fcmp ogt double",
                    BinOp::Ge => "fcmp oge double",
                    _ => unreachable!(),
                };
                self.emit(format!("{r} = {inst} {a}, {b}"));
            }
            Type::Bool => {
                let cc = if op == BinOp::Eq { "eq" } else { "ne" };
                self.emit(format!("{r} = icmp {cc} i1 {a}, {b}"));
            }
            Type::Str => match op {
                BinOp::Add => self.emit(format!("{r} = call ptr @isma_str_concat(ptr {a}, ptr {b})")),
                BinOp::Eq | BinOp::Ne => {
                    let eq = self.fresh();
                    self.emit(format!("{eq} = call i64 @isma_str_eq(ptr {a}, ptr {b})"));
                    let cc = if op == BinOp::Eq { "ne" } else { "eq" };
                    self.emit(format!("{r} = icmp {cc} i64 {eq}, 0"));
                }
                _ => {
                    let c = self.fresh();
                    self.emit(format!("{c} = call i64 @isma_str_cmp(ptr {a}, ptr {b})"));
                    let cc = match op {
                        BinOp::Lt => "slt",
                        BinOp::Le => "sle",
                        BinOp::Gt => "sgt",
                        BinOp::Ge => "sge",
                        _ => unreachable!(),
                    };
                    self.emit(format!("{r} = icmp {cc} i64 {c}, 0"));
                }
            },
            _ => unreachable!("binary op on {ty:?}"),
        }
        r
    }

    fn emit_to_string(&mut self, ty: &Type, v: &str) -> String {
        let r = self.fresh();
        match ty {
            Type::Str => return v.to_string(),
            Type::Int => self.emit(format!("{r} = call ptr @isma_int_to_str(i64 {v})")),
            Type::Float => self.emit(format!("{r} = call ptr @isma_float_to_str(double {v})")),
            Type::Bool => {
                let z = self.fresh();
                self.emit(format!("{z} = zext i1 {v} to i64"));
                self.emit(format!("{r} = call ptr @isma_bool_to_str(i64 {z})"));
            }
            _ => unreachable!(),
        }
        r
    }

    /// Evaluate an rvalue; returns the LLVM value (empty for unit).
    fn rvalue(&mut self, r: &Rvalue) -> String {
        match r {
            Rvalue::Use(o) => self.operand(o),
            Rvalue::Binary(op, ty, a, b, span) => {
                let a = self.operand(a);
                let b = self.operand(b);
                self.binop_values(*op, ty, &a, &b, *span)
            }
            Rvalue::Neg(ty, x, span) => {
                let v = self.operand(x);
                if *ty == Type::Int {
                    self.checked_int("ssub", "0", &v, *span)
                } else {
                    let r = self.fresh();
                    self.emit(format!("{r} = fneg double {v}"));
                    r
                }
            }
            Rvalue::Not(x) => {
                let v = self.operand(x);
                let r = self.fresh();
                self.emit(format!("{r} = xor i1 {v}, true"));
                r
            }
            Rvalue::Call(fid, args, span) => {
                let mut vals = Vec::new();
                for a in args {
                    let ty = llty(&self.f.operand_ty(a));
                    let v = self.operand(a);
                    vals.push(format!("{ty} {v}"));
                }
                let callee = &self.prog.funcs[*fid];
                if callee.track_caller {
                    vals.push(self.loc(*span));
                }
                let sym = callee.symbol.clone();
                if callee.ret == Type::Unit {
                    self.emit(format!("call void @{sym}({})", vals.join(", ")));
                    String::new()
                } else {
                    let rt = llty(&callee.ret);
                    let r = self.fresh();
                    self.emit(format!("{r} = call {rt} @{sym}({})", vals.join(", ")));
                    r
                }
            }
            Rvalue::Builtin(b, args, span) => self.builtin(*b, args, *span),
            Rvalue::Field(obj, sid, idx) => {
                let o = self.operand(&Operand::Var(*obj));
                let s = &self.prog.structs[*sid];
                let sname = s.name.clone();
                let ft = llty(&s.fields[*idx].ty);
                let p = self.fresh();
                self.emit(format!("{p} = getelementptr inbounds %struct.{sname}, ptr {o}, i32 0, i32 {}", idx + 1));
                let r = self.fresh();
                let md = self.field_tbaa(*sid, *idx);
                self.emit(format!("{r} = load {ft}, ptr {p}{md}"));
                r
            }
            Rvalue::Index(list, index, span) => {
                let elem = list_elem(&self.f.vars[*list].ty);
                let l = self.operand(&Operand::Var(*list));
                let i = self.operand(index);
                let p = self.list_elem_ptr(&l, &i, &elem, *span);
                let r = self.fresh();
                let md = self.elem_tbaa(&elem);
                self.emit(format!("{r} = load {}, ptr {p}{md}", llty(&elem)));
                r
            }
            Rvalue::StructNew(sid, args) | Rvalue::Reuse(_, sid, args) => {
                let vals: Vec<(String, Type)> = args.iter().map(|a| (self.operand(a), self.f.operand_ty(a))).collect();
                let sname = self.prog.structs[*sid].name.clone();
                let szp = self.fresh();
                self.emit(format!("{szp} = getelementptr %struct.{sname}, ptr null, i32 1"));
                let sz = self.fresh();
                self.emit(format!("{sz} = ptrtoint ptr {szp} to i64"));
                let p = self.fresh();
                if let Rvalue::Reuse(tok, ..) = r {
                    // Build in the reused memory when there is some.
                    let t = self.operand(&Operand::Var(*tok));
                    let none = self.fresh();
                    self.emit(format!("{none} = icmp eq ptr {t}, null"));
                    let from = self.cur_label.clone();
                    let la = self.new_label("reuse.alloc");
                    let ld = self.new_label("reuse.have");
                    self.emit_term(format!("br i1 {none}, label %{la}, label %{ld}"));
                    self.start_block(&la);
                    let m = self.fresh();
                    self.emit(format!("{m} = call ptr @isma_alloc(i64 {sz})"));
                    self.br(&ld);
                    self.start_block(&ld);
                    self.emit(format!("{p} = phi ptr [ {m}, %{la} ], [ {t}, %{from} ]"));
                } else {
                    self.emit(format!("{p} = call ptr @isma_alloc(i64 {sz})"));
                }
                let md = self.tbaa("rc");
                let one = if self.is_cyclic(&Type::Struct(*sid)) { 8 } else { 1 };
                self.emit(format!("store i64 {one}, ptr {p}{md}"));
                for (i, (v, ty)) in vals.iter().enumerate() {
                    let fp = self.fresh();
                    self.emit(format!("{fp} = getelementptr inbounds %struct.{sname}, ptr {p}, i32 0, i32 {}", i + 1));
                    let md = self.field_tbaa(*sid, i);
                    self.emit(format!("store {} {v}, ptr {fp}{md}", llty(ty)));
                }
                p
            }
            Rvalue::ListNew(elem, args) => {
                let sz = elem_size(elem);
                let l = self.fresh();
                self.emit(format!("{l} = call ptr @isma_list_new(i64 {sz}, i64 {})", args.len()));
                if self.is_cyclic(&Type::List(Box::new(elem.clone()))) {
                    let md = self.tbaa("rc");
                    self.emit(format!("store i64 8, ptr {l}{md}"));
                }
                for a in args {
                    let v = self.operand(a);
                    let slot = self.push_slot(&l, elem);
                    let md = self.elem_tbaa(elem);
                    self.emit(format!("store {} {v}, ptr {slot}{md}", llty(elem)));
                }
                l
            }
        }
    }

    fn builtin(&mut self, b: Builtin, args: &[Operand], span: Span) -> String {
        let tys: Vec<Type> = args.iter().map(|a| self.f.operand_ty(a)).collect();
        let vals: Vec<String> = args.iter().map(|a| self.operand(a)).collect();
        let r = self.fresh();
        let loc = self.loc(span);
        match b {
            Builtin::Print => {
                let v = &vals[0];
                match &tys[0] {
                    Type::Int => self.emit(format!("call void @isma_print_int(i64 {v})")),
                    Type::Float => self.emit(format!("call void @isma_print_float(double {v})")),
                    Type::Str => self.emit(format!("call void @isma_print_str(ptr {v})")),
                    Type::Bool => {
                        self.emit(format!("{r} = zext i1 {v} to i64"));
                        self.emit(format!("call void @isma_print_bool(i64 {r})"));
                    }
                    _ => unreachable!(),
                }
                return String::new();
            }
            Builtin::Input => self.emit(format!("{r} = call ptr @isma_input()")),
            Builtin::Args => self.emit(format!("{r} = call ptr @isma_args()")),
            Builtin::Panic => {
                self.emit(format!("call void @isma_panic_msg(ptr {}, {loc})", vals[0]));
                return String::new();
            }
            Builtin::Exit => {
                self.emit(format!("call void @isma_exit(i64 {})", vals[0]));
                return String::new();
            }
            Builtin::Assert => {
                let failed = self.fresh();
                self.emit(format!("{failed} = xor i1 {}, true", vals[0]));
                self.panic_if(&failed, format!("call void @isma_assert_fail({loc})"));
                return String::new();
            }
            Builtin::Sqrt => self.emit(format!("{r} = call double @llvm.sqrt.f64(double {})", vals[0])),
            Builtin::IntToFloat => self.emit(format!("{r} = sitofp i64 {} to double", vals[0])),
            Builtin::FloatToInt => self.emit(format!("{r} = call i64 @llvm.fptosi.sat.i64.f64(double {})", vals[0])),
            Builtin::StrToInt => self.emit(format!("{r} = call i64 @isma_str_to_int(ptr {}, {loc})", vals[0])),
            Builtin::StrToFloat => self.emit(format!("{r} = call double @isma_str_to_float(ptr {}, {loc})", vals[0])),
            Builtin::StrChars => self.emit(format!("{r} = call ptr @isma_str_chars(ptr {})", vals[0])),
            Builtin::StrSubstring => {
                self.emit(format!("{r} = call ptr @isma_str_substring(ptr {}, i64 {}, i64 {}, {loc})", vals[0], vals[1], vals[2]))
            }
            Builtin::StrContains | Builtin::StrStartsWith | Builtin::StrEndsWith => {
                let f = match b {
                    Builtin::StrContains => "isma_str_contains",
                    Builtin::StrStartsWith => "isma_str_starts_with",
                    _ => "isma_str_ends_with",
                };
                let raw = self.fresh();
                self.emit(format!("{raw} = call i64 @{f}(ptr {}, ptr {})", vals[0], vals[1]));
                self.emit(format!("{r} = icmp ne i64 {raw}, 0"));
            }
            Builtin::RealtimeNs => self.emit(format!("{r} = call i64 @isma_time_realtime_ns()")),
            Builtin::MonotonicNs => self.emit(format!("{r} = call i64 @isma_time_monotonic_ns()")),
            Builtin::SleepNs => {
                self.emit(format!("call void @isma_time_sleep_ns(i64 {})", vals[0]));
                return String::new();
            }
            Builtin::ToStr => return self.emit_to_string(&tys[0], &vals[0]),
            Builtin::StrLen => {
                let lp = self.fresh();
                self.emit(format!("{lp} = getelementptr inbounds i8, ptr {}, i64 8", vals[0]));
                let md = self.tbaa("str.len");
                self.emit(format!("{r} = load i64, ptr {lp}{md}"));
            }
            Builtin::ListLen => return self.list_len(&vals[0]),
            Builtin::StrAppendOwned => self.emit(format!("{r} = call ptr @isma_str_append_owned(ptr {}, ptr {})", vals[0], vals[1])),
            Builtin::ListPush => {
                let elem = list_elem(&tys[0]);
                let slot = self.push_slot(&vals[0], &elem);
                let md = self.elem_tbaa(&elem);
                self.emit(format!("store {} {}, ptr {slot}{md}", llty(&elem), vals[1]));
                return String::new();
            }
            Builtin::ListPop => {
                let elem = list_elem(&tys[0]);
                let sz = elem_size(&elem);
                let slot = self.fresh();
                self.emit(format!("{slot} = call ptr @isma_list_pop_slot(ptr {}, i64 {sz}, {loc})", vals[0]));
                let md = self.elem_tbaa(&elem);
                self.emit(format!("{r} = load {}, ptr {slot}{md}", llty(&elem)));
            }
            Builtin::Inc => self.emit(format!("{r} = add nsw i64 {}, 1", vals[0])),
        }
        r
    }
}
