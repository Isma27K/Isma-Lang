//! LLVM IR (textual) code generator, from MIR.
//!
//! Strategy: every MIR variable lives in an `alloca` in the entry block;
//! clang's mem2reg/SROA passes promote them to SSA registers, so the output
//! is as fast as hand-written SSA after `-O2`/`-O3`.

use crate::ast::BinOp;
use crate::mir::*;
use crate::span::{SourceMap, Span};
use crate::tast::Builtin;
use crate::types::*;
use std::collections::HashMap;
use std::fmt::Write as _;

pub fn generate(prog: &Program, sources: &SourceMap, target_triple: Option<&str>) -> String {
    // LLVM type names: the struct's name (`Box[Int]` becomes `Box.Int.`), made
    // unique when two modules (`a/util.isma`, `b/util.isma`) define types
    // with the same name.
    let safe: Vec<String> = prog.structs.iter().map(|s| llvm_name(&s.name)).collect();
    let type_names: Vec<String> =
        safe.iter().enumerate().map(|(sid, n)| if safe.iter().filter(|o| *o == n).count() > 1 { format!("{n}.{sid}") } else { n.clone() }).collect();
    let mut g = Codegen {
        prog,
        type_names,
        sources,
        f: &prog.funcs[0],
        caller_loc: None,
        strings: HashMap::new(),
        globals: String::new(),
        body: String::new(),
        allocas: String::new(),
        tmp: 0,
        label: 0,
        cur_label: String::new(),
        terminated: false,
        tbaa: Vec::new(),
        rc_types: Vec::new(),
        cyclic: HashMap::new(),
        units: Vec::new(),
        name_tables: Vec::new(),
    };
    let mut funcs = String::new();
    for f in prog.funcs.iter().filter(|f| !f.generic) {
        funcs.push_str(&g.function(f));
    }
    funcs.push_str(&g.rc_functions());

    let mut out = String::new();
    let _ = writeln!(out, "; generated by the Isma compiler v{}", env!("CARGO_PKG_VERSION"));
    let _ = writeln!(out, "source_filename = \"{}\"", escape_bytes(sources.file_name(0).as_bytes()));
    if let Some(t) = target_triple {
        let _ = writeln!(out, "target triple = \"{t}\"");
    }
    out.push('\n');
    // Every heap object starts with its reference count.
    out.push_str("%IsmaList = type { i64, i64, i64, ptr }\n");
    for (s, tname) in prog.structs.iter().zip(&g.type_names) {
        if s.generic {
            continue;
        }
        match &s.variants {
            // Every variant of an enum with data: { rc, tag, fields... }
            Some(variants) => {
                for v in variants {
                    let fields: Vec<&str> = ["i64", "i64"].into_iter().chain(v.fields.iter().map(|f| llty(&f.ty))).collect();
                    let _ = writeln!(out, "%enum.{tname}.{} = type {{ {} }}", v.name, fields.join(", "));
                }
            }
            None => {
                let fields: Vec<&str> = std::iter::once("i64").chain(s.fields.iter().map(|f| llty(&f.ty))).collect();
                let _ = writeln!(out, "%struct.{tname} = type {{ {} }}", fields.join(", "));
            }
        }
    }
    out.push('\n');
    // File names for panic messages: the user's file, then imported modules.
    for i in 0..sources.file_count() {
        let file = sources.file_name(i).as_bytes();
        let _ = writeln!(out, "@.file.{i} = private unnamed_addr constant [{} x i8] c\"{}\\00\"", file.len() + 1, escape_bytes(file));
    }
    out.push_str(&g.globals);
    out.push('\n');
    out.push_str(RUNTIME_DECLS);
    out.push('\n');
    out.push_str(&funcs);
    out.push_str("attributes #0 = { nounwind }\n");
    out.push_str("attributes #1 = { cold noreturn nounwind }\n");
    out.push_str("attributes #2 = { alwaysinline nounwind }\n");
    // Type-based alias analysis: Isma has no pointer casts, so memory of
    // different kinds (list headers, elements of each type, each struct
    // field) can never overlap. Telling LLVM lets it keep e.g. a list's
    // length in a register while storing into its elements.
    if !g.tbaa.is_empty() {
        out.push_str("\n!0 = !{!\"isma.tbaa\"}\n");
        for (i, name) in g.tbaa.iter().enumerate() {
            let ty = 2 * i + 1;
            let _ = writeln!(out, "!{ty} = !{{!\"{name}\", !0, i64 0}}");
            let _ = writeln!(out, "!{} = !{{!{ty}, !{ty}, i64 0}}", ty + 1);
        }
    }
    out
}

