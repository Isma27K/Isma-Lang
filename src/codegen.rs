fn llty(t: &Type) -> &'static str {
    match t {
        Type::Int => "i64",
        Type::Float => "double",
        Type::Bool => "i1",
        Type::Str | Type::List(_) | Type::Struct(_) => "ptr",
        Type::Unit => "void",
        Type::Error => unreachable!("error type reached codegen"),
    }
}

/// Size in bytes of a list element of this type.
fn elem_size(t: &Type) -> u64 {
    match t {
        Type::Bool => 1,
        _ => 8,
    }
}

fn escape_bytes(b: &[u8]) -> String {
    let mut s = String::new();
    for &c in b {
        if (0x20..0x7f).contains(&c) && c != b'"' && c != b'\\' {
            s.push(c as char);
        } else {
            let _ = write!(s, "\\{c:02X}");
        }
    }
    s
}

fn float_const(v: f64) -> String {
    format!("0x{:016X}", v.to_bits())
}

struct Codegen<'a> {
    prog: &'a TProgram,
    sources: &'a SourceMap<'a>,
    /// Inside a `track_caller` function: the caller's location arguments.
    caller_loc: Option<String>,
    strings: HashMap<String, String>,
    globals: String,
    // per-function state
    body: String,
    allocas: String,
    tmp: usize,
    label: usize,
    cur_label: String,
    terminated: bool,
    /// (continue target, break target)
    loops: Vec<(String, String)>,
    locals: Vec<TLocal>,
    /// TBAA alias classes, by name, in creation order.
    tbaa: Vec<String>,
}

impl<'a> Codegen<'a> {
    // ---------- emission helpers ----------

    fn fresh(&mut self) -> String {
        self.tmp += 1;
        format!("%t{}", self.tmp)
    }

    fn new_label(&mut self, hint: &str) -> String {
        self.label += 1;
        format!("{hint}{}", self.label)
    }

    /// Emit an instruction. If the current block already ended (e.g. after a
    /// `return`), the instruction goes into a fresh unreachable block.
    fn emit(&mut self, s: impl AsRef<str>) {
        if self.terminated {
            let l = self.new_label("dead");
            let _ = writeln!(self.body, "{l}:");
            self.cur_label = l;
            self.terminated = false;
        }
        self.body.push_str("  ");
        self.body.push_str(s.as_ref());
        self.body.push('\n');
    }

    fn emit_term(&mut self, s: impl AsRef<str>) {
        self.emit(s);
        self.terminated = true;
    }

    fn br(&mut self, label: &str) {
        if !self.terminated {
            self.emit_term(format!("br label %{label}"));
        }
    }

    fn start_block(&mut self, label: &str) {
        self.br(label);
        let _ = writeln!(self.body, "{label}:");
        self.cur_label = label.to_string();
        self.terminated = false;
    }

    /// `, !tbaa !N` suffix for a memory access of the given alias class.
    fn tbaa(&mut self, class: &str) -> String {
        let i = match self.tbaa.iter().position(|c| c == class) {
            Some(i) => i,
            None => {
                self.tbaa.push(class.to_string());
                self.tbaa.len() - 1
            }
        };
        format!(", !tbaa !{}", 2 * i + 2)
    }

    fn elem_tbaa(&mut self, elem: &Type) -> String {
        let class = format!("list.elem.{}", llty(elem));
        self.tbaa(&class)
    }

    fn field_tbaa(&mut self, sid: StructId, idx: usize) -> String {
        let class = format!("field.{}.{idx}", self.prog.structs[sid].name);
        self.tbaa(&class)
    }

    fn alloca(&mut self, ty: &str) -> String {
        self.tmp += 1;
        let name = format!("%s{}", self.tmp);
        let _ = writeln!(self.allocas, "  {name} = alloca {ty}");
        name
    }

    /// `ptr file, i32 line, i32 col` arguments for runtime panics.
    fn loc(&self, span: Span) -> String {
        if let Some(caller) = &self.caller_loc {
            return caller.clone();
        }
        let (file, line, col) = self.sources.locate(span.start);
        format!("ptr @.file.{file}, i32 {line}, i32 {col}")
    }

    /// Branch to a cold panic block when `cond` is true.
    fn panic_if(&mut self, cond: &str, panic_call: String) {
        let bad = self.new_label("panic");
        let ok = self.new_label("ok");
        self.emit_term(format!("br i1 {cond}, label %{bad}, label %{ok}"));
        self.start_block(&bad);
        self.emit(panic_call);
        self.emit_term("unreachable");
        self.start_block(&ok);
    }

    fn string_literal(&mut self, s: &str) -> String {
        if let Some(name) = self.strings.get(s) {
            return name.clone();
        }
        let name = format!("@.str.{}", self.strings.len());
        let b = s.as_bytes();
        let _ = writeln!(
            self.globals,
            "{name} = private unnamed_addr constant {{ i64, [{n} x i8] }} {{ i64 {n}, [{n} x i8] c\"{}\" }}, align 8",
            escape_bytes(b),
            n = b.len()
        );
        self.strings.insert(s.to_string(), name.clone());
        name
    }

    // ---------- functions ----------

    fn function(&mut self, f: &TFunc) -> String {
        self.body.clear();
        self.allocas.clear();
        self.tmp = 0;
        self.label = 0;
        self.cur_label = "entry".into();
        self.terminated = false;
        self.loops.clear();
        self.locals = f.locals.clone();
        self.caller_loc = f.track_caller.then(|| "ptr %caller.file, i32 %caller.line, i32 %caller.col".to_string());

        for (id, l) in f.locals.iter().enumerate() {
            let _ = writeln!(self.allocas, "  %l{id} = alloca {}", llty(&l.ty));
        }
        let mut params = Vec::new();
        for (i, &id) in f.params.iter().enumerate() {
            let ty = llty(&f.locals[id].ty);
            params.push(format!("{ty} %a{i}"));
            self.emit(format!("store {ty} %a{i}, ptr %l{id}"));
        }
        if f.track_caller {
            params.push("ptr %caller.file, i32 %caller.line, i32 %caller.col".to_string());
        }
        self.stmts(&f.body);
        if !self.terminated {
            if f.ret == Type::Unit {
                self.emit_term("ret void");
            } else {
                self.emit_term("unreachable");
            }
        }
        let linkage = if f.exported { "" } else { "internal " };
        format!(
            "; {}\ndefine {linkage}{} @{}({}) #0 {{\nentry:\n{}{}}}\n\n",
            f.name,
            llty(&f.ret),
            f.symbol,
            params.join(", "),
            self.allocas,
            self.body
        )
    }

    // ---------- statements ----------

    fn stmts(&mut self, stmts: &[TStmt]) {
        for s in stmts {
            self.stmt(s);
        }
    }

    fn stmt(&mut self, s: &TStmt) {
        match s {
            TStmt::Let(id, e) => {
                let v = self.expr(e);
                let ty = llty(&self.locals[*id].ty);
                self.emit(format!("store {ty} {v}, ptr %l{id}"));
            }
            TStmt::Assign { place, op, value, span } => {
                // Evaluate the value first: it may grow a list and move its buffer.
                let v = self.expr(value);
                let (addr, ty) = match place {
                    Place::Local(id) => (format!("%l{id}"), self.locals[*id].ty.clone()),
                    Place::Field { obj, sid, idx } => {
                        let o = self.expr(obj);
                        let p = self.fresh();
                        let sname = &self.prog.structs[*sid].name;
                        self.emit(format!("{p} = getelementptr inbounds %struct.{sname}, ptr {o}, i32 0, i32 {idx}"));
                        (p, self.prog.structs[*sid].fields[*idx].ty.clone())
                    }
                    Place::Index { list, index, span } => {
                        let elem = match &list.ty {
                            Type::List(t) => (**t).clone(),
                            _ => unreachable!(),
                        };
                        let l = self.expr(list);
                        let i = self.expr(index);
                        (self.list_elem_ptr(&l, &i, &elem, *span), elem)
                    }
                };
                let lt = llty(&ty);
                let md = match place {
                    Place::Local(_) => String::new(),
                    Place::Field { sid, idx, .. } => self.field_tbaa(*sid, *idx),
                    Place::Index { .. } => self.elem_tbaa(&ty),
                };
                let newv = match op {
                    None => v,
                    Some(op) => {
                        let cur = self.fresh();
                        self.emit(format!("{cur} = load {lt}, ptr {addr}{md}"));
                        self.binop_values(*op, &ty, &cur, &v, *span)
                    }
                };
                self.emit(format!("store {lt} {newv}, ptr {addr}{md}"));
            }
            TStmt::Expr(e) => {
                self.expr(e);
            }
            TStmt::If { branches, else_block } => {
                let end = self.new_label("endif");
                for (cond, body) in branches {
                    let c = self.expr(cond);
                    let then = self.new_label("then");
                    let next = self.new_label("else");
                    self.emit_term(format!("br i1 {c}, label %{then}, label %{next}"));
                    self.start_block(&then);
                    self.stmts(body);
                    self.br(&end);
                    self.start_block(&next);
                }
                if let Some(b) = else_block {
                    self.stmts(b);
                }
                self.start_block(&end);
            }
            TStmt::While { cond, body } => {
                let lc = self.new_label("while.cond");
                let lb = self.new_label("while.body");
                let le = self.new_label("while.end");
                self.start_block(&lc);
                let c = self.expr(cond);
                self.emit_term(format!("br i1 {c}, label %{lb}, label %{le}"));
                self.start_block(&lb);
                self.loops.push((lc.clone(), le.clone()));
                self.stmts(body);
                self.loops.pop();
                self.br(&lc);
                self.start_block(&le);
            }
            TStmt::ForRange { var, start, end, inclusive, body } => {
                let s = self.expr(start);
                let e = self.expr(end);
                let ctr = self.alloca("i64");
                self.emit(format!("store i64 {s}, ptr {ctr}"));
                let lc = self.new_label("for.cond");
                let lb = self.new_label("for.body");
                let ls = self.new_label("for.step");
                let le = self.new_label("for.end");
                self.start_block(&lc);
                let i = self.fresh();
                self.emit(format!("{i} = load i64, ptr {ctr}"));
                let c = self.fresh();
                let cmp = if *inclusive { "sle" } else { "slt" };
                self.emit(format!("{c} = icmp {cmp} i64 {i}, {e}"));
                self.emit_term(format!("br i1 {c}, label %{lb}, label %{le}"));
                self.start_block(&lb);
                let i2 = self.fresh();
                self.emit(format!("{i2} = load i64, ptr {ctr}"));
                self.emit(format!("store i64 {i2}, ptr %l{var}"));
                self.loops.push((ls.clone(), le.clone()));
                self.stmts(body);
                self.loops.pop();
                self.start_block(&ls);
                let i3 = self.fresh();
                self.emit(format!("{i3} = load i64, ptr {ctr}"));
                if *inclusive {
                    // Stop before incrementing past `end` (avoids overflow at Int max).
                    let at_end = self.fresh();
                    self.emit(format!("{at_end} = icmp eq i64 {i3}, {e}"));
                    let inc = self.new_label("for.inc");
                    self.emit_term(format!("br i1 {at_end}, label %{le}, label %{inc}"));
                    self.start_block(&inc);
                }
                let n = self.fresh();
                self.emit(format!("{n} = add nsw i64 {i3}, 1"));
                self.emit(format!("store i64 {n}, ptr {ctr}"));
                self.br(&lc);
                self.start_block(&le);
            }
            TStmt::ForList { var, list, body } => {
                let elem = match &list.ty {
                    Type::List(t) => (**t).clone(),
                    _ => unreachable!(),
                };
                let et = llty(&elem);
                let l = self.expr(list);
                let ctr = self.alloca("i64");
                self.emit(format!("store i64 0, ptr {ctr}"));
                let lc = self.new_label("for.cond");
                let lb = self.new_label("for.body");
                let ls = self.new_label("for.step");
                let le = self.new_label("for.end");
                self.start_block(&lc);
                let i = self.fresh();
                self.emit(format!("{i} = load i64, ptr {ctr}"));
                let len = self.fresh();
                let md_len = self.tbaa("list.len");
                self.emit(format!("{len} = load i64, ptr {l}{md_len}"));
                let c = self.fresh();
                self.emit(format!("{c} = icmp slt i64 {i}, {len}"));
                self.emit_term(format!("br i1 {c}, label %{lb}, label %{le}"));
                self.start_block(&lb);
                let dp = self.fresh();
                self.emit(format!("{dp} = getelementptr inbounds %IsmaList, ptr {l}, i32 0, i32 2"));
                let data = self.fresh();
                let md_data = self.tbaa("list.data");
                self.emit(format!("{data} = load ptr, ptr {dp}{md_data}"));
                let ep = self.fresh();
                self.emit(format!("{ep} = getelementptr inbounds {et}, ptr {data}, i64 {i}"));
                let v = self.fresh();
                let md_elem = self.elem_tbaa(&elem);
                self.emit(format!("{v} = load {et}, ptr {ep}{md_elem}"));
                self.emit(format!("store {et} {v}, ptr %l{var}"));
                self.loops.push((ls.clone(), le.clone()));
                self.stmts(body);
                self.loops.pop();
                self.start_block(&ls);
                let i3 = self.fresh();
                self.emit(format!("{i3} = load i64, ptr {ctr}"));
                let n = self.fresh();
                self.emit(format!("{n} = add nsw i64 {i3}, 1"));
                self.emit(format!("store i64 {n}, ptr {ctr}"));
                self.br(&lc);
                self.start_block(&le);
            }
            TStmt::Break => {
                let target = self.loops.last().expect("break outside loop").1.clone();
                self.br(&target);
            }
            TStmt::Continue => {
                let target = self.loops.last().expect("continue outside loop").0.clone();
                self.br(&target);
            }
            TStmt::Return(None) => self.emit_term("ret void"),
            TStmt::Return(Some(e)) => {
                let v = self.expr(e);
                if e.ty == Type::Unit {
                    self.emit_term("ret void");
                } else {
                    let t = llty(&e.ty);
                    self.emit_term(format!("ret {t} {v}"));
                }
            }
        }
    }

    // ---------- expressions ----------

    /// Returns a pointer to element `i` of `list`, with a bounds check.
    fn list_elem_ptr(&mut self, list: &str, i: &str, elem: &Type, span: Span) -> String {
        let len = self.fresh();
        let md_len = self.tbaa("list.len");
        self.emit(format!("{len} = load i64, ptr {list}{md_len}"));
        let oob = self.fresh();
        self.emit(format!("{oob} = icmp uge i64 {i}, {len}"));
        let loc = self.loc(span);
        self.panic_if(&oob, format!("call void @isma_panic_bounds(i64 {i}, i64 {len}, {loc})"));
        let dp = self.fresh();
        self.emit(format!("{dp} = getelementptr inbounds %IsmaList, ptr {list}, i32 0, i32 2"));
        let data = self.fresh();
        let md_data = self.tbaa("list.data");
        self.emit(format!("{data} = load ptr, ptr {dp}{md_data}"));
        let ep = self.fresh();
        self.emit(format!("{ep} = getelementptr inbounds {}, ptr {data}, i64 {i}", llty(elem)));
        ep
    }

    /// Reserve a slot at the end of `list`. The common case (spare capacity)
    /// is inlined; only growth calls into the runtime.
    fn push_slot(&mut self, list: &str, elem: &Type) -> String {
        let sz = elem_size(elem);
        let md_len = self.tbaa("list.len");
        let md_cap = self.tbaa("list.cap");
        let md_data = self.tbaa("list.data");
        let len = self.fresh();
        self.emit(format!("{len} = load i64, ptr {list}{md_len}"));
        let capp = self.fresh();
        self.emit(format!("{capp} = getelementptr inbounds %IsmaList, ptr {list}, i32 0, i32 1"));
        let cap = self.fresh();
        self.emit(format!("{cap} = load i64, ptr {capp}{md_cap}"));
        let full = self.fresh();
        self.emit(format!("{full} = icmp eq i64 {len}, {cap}"));
        let grow = self.new_label("push.grow");
        let fast = self.new_label("push.fast");
        let done = self.new_label("push.done");
        self.emit_term(format!("br i1 {full}, label %{grow}, label %{fast}"));
        self.start_block(&grow);
        let slow = self.fresh();
        self.emit(format!("{slow} = call ptr @isma_list_push_slot(ptr {list}, i64 {sz})"));
        self.br(&done);
        self.start_block(&fast);
        let dp = self.fresh();
        self.emit(format!("{dp} = getelementptr inbounds %IsmaList, ptr {list}, i32 0, i32 2"));
        let data = self.fresh();
        self.emit(format!("{data} = load ptr, ptr {dp}{md_data}"));
        let quick = self.fresh();
        self.emit(format!("{quick} = getelementptr inbounds {}, ptr {data}, i64 {len}", llty(elem)));
        let newlen = self.fresh();
        self.emit(format!("{newlen} = add nsw i64 {len}, 1"));
        self.emit(format!("store i64 {newlen}, ptr {list}{md_len}"));
        self.br(&done);
        self.start_block(&done);
        let slot = self.fresh();
        self.emit(format!("{slot} = phi ptr [ {slow}, %{grow} ], [ {quick}, %{fast} ]"));
        slot
    }

    fn checked_int(&mut self, intrinsic: &str, a: &str, b: &str, span: Span) -> String {
        let r = self.fresh();
        self.emit(format!("{r} = call {{ i64, i1 }} @llvm.{intrinsic}.with.overflow.i64(i64 {a}, i64 {b})"));
        let v = self.fresh();
        self.emit(format!("{v} = extractvalue {{ i64, i1 }} {r}, 0"));
        let o = self.fresh();
        self.emit(format!("{o} = extractvalue {{ i64, i1 }} {r}, 1"));
        let loc = self.loc(span);
        self.panic_if(&o, format!("call void @isma_panic_overflow({loc})"));
        v
    }

    /// Apply a (non-short-circuit) binary operator to already-evaluated operands.
    fn binop_values(&mut self, op: BinOp, ty: &Type, a: &str, b: &str, span: Span) -> String {
        let r = self.fresh();
        match ty {
            Type::Int => match op {
                BinOp::Add => return self.checked_int("sadd", a, b, span),
                BinOp::Sub => return self.checked_int("ssub", a, b, span),
                BinOp::Mul => return self.checked_int("smul", a, b, span),
                BinOp::Div | BinOp::Mod => {
                    let loc = self.loc(span);
                    let z = self.fresh();
                    self.emit(format!("{z} = icmp eq i64 {b}, 0"));
                    self.panic_if(&z, format!("call void @isma_panic_divzero({loc})"));
                    let m1 = self.fresh();
                    self.emit(format!("{m1} = icmp eq i64 {a}, {}", i64::MIN));
                    let m2 = self.fresh();
                    self.emit(format!("{m2} = icmp eq i64 {b}, -1"));
                    let both = self.fresh();
                    self.emit(format!("{both} = and i1 {m1}, {m2}"));
                    self.panic_if(&both, format!("call void @isma_panic_overflow({loc})"));
                    let inst = if op == BinOp::Div { "sdiv" } else { "srem" };
                    self.emit(format!("{r} = {inst} i64 {a}, {b}"));
                }
                _ => {
                    let cc = match op {
                        BinOp::Eq => "eq",
                        BinOp::Ne => "ne",
                        BinOp::Lt => "slt",
                        BinOp::Le => "sle",
                        BinOp::Gt => "sgt",
                        BinOp::Ge => "sge",
                        _ => unreachable!(),
                    };
                    self.emit(format!("{r} = icmp {cc} i64 {a}, {b}"));
                }
            },
            Type::Float => {
                let inst = match op {
                    BinOp::Add => "fadd double",
                    BinOp::Sub => "fsub double",
                    BinOp::Mul => "fmul double",
                    BinOp::Div => "fdiv double",
                    BinOp::Mod => "frem double",
                    BinOp::Eq => "fcmp oeq double",
                    BinOp::Ne => "fcmp une double",
                    BinOp::Lt => "fcmp olt double",
                    BinOp::Le => "fcmp ole double",
                    BinOp::Gt => "fcmp ogt double",
                    BinOp::Ge => "fcmp oge double",
                    _ => unreachable!(),
                };
                self.emit(format!("{r} = {inst} {a}, {b}"));
            }
            Type::Bool => {
                let cc = if op == BinOp::Eq { "eq" } else { "ne" };
                self.emit(format!("{r} = icmp {cc} i1 {a}, {b}"));
            }
            Type::Str => match op {
                BinOp::Add => self.emit(format!("{r} = call ptr @isma_str_concat(ptr {a}, ptr {b})")),
                BinOp::Eq | BinOp::Ne => {
                    let eq = self.fresh();
                    self.emit(format!("{eq} = call i64 @isma_str_eq(ptr {a}, ptr {b})"));
                    let cc = if op == BinOp::Eq { "ne" } else { "eq" };
                    self.emit(format!("{r} = icmp {cc} i64 {eq}, 0"));
                }
                _ => {
                    let c = self.fresh();
                    self.emit(format!("{c} = call i64 @isma_str_cmp(ptr {a}, ptr {b})"));
                    let cc = match op {
                        BinOp::Lt => "slt",
                        BinOp::Le => "sle",
                        BinOp::Gt => "sgt",
                        BinOp::Ge => "sge",
                        _ => unreachable!(),
                    };
                    self.emit(format!("{r} = icmp {cc} i64 {c}, 0"));
                }
            },
            _ => unreachable!("binary op on {ty:?}"),
        }
        r
    }

    fn short_circuit(&mut self, is_and: bool, l: &TExpr, r: &TExpr) -> String {
        let a = self.expr(l);
        let from = self.cur_label.clone();
        let rhs = self.new_label(if is_and { "and.rhs" } else { "or.rhs" });
        let end = self.new_label(if is_and { "and.end" } else { "or.end" });
        if is_and {
            self.emit_term(format!("br i1 {a}, label %{rhs}, label %{end}"));
        } else {
            self.emit_term(format!("br i1 {a}, label %{end}, label %{rhs}"));
        }
        self.start_block(&rhs);
        let b = self.expr(r);
        let rhs_end = self.cur_label.clone();
        self.br(&end);
        self.start_block(&end);
        let res = self.fresh();
        let short = if is_and { "false" } else { "true" };
        self.emit(format!("{res} = phi i1 [ {short}, %{from} ], [ {b}, %{rhs_end} ]"));
        res
    }

    fn emit_to_string(&mut self, ty: &Type, v: &str) -> String {
        let r = self.fresh();
        match ty {
            Type::Str => return v.to_string(),
            Type::Int => self.emit(format!("{r} = call ptr @isma_int_to_str(i64 {v})")),
            Type::Float => self.emit(format!("{r} = call ptr @isma_float_to_str(double {v})")),
            Type::Bool => {
                let z = self.fresh();
                self.emit(format!("{z} = zext i1 {v} to i64"));
                self.emit(format!("{r} = call ptr @isma_bool_to_str(i64 {z})"));
            }
            _ => unreachable!(),
        }
        r
    }

    fn expr(&mut self, e: &TExpr) -> String {
        match &e.kind {
            TExprKind::Int(v) => v.to_string(),
            TExprKind::Float(v) => float_const(*v),
            TExprKind::Bool(v) => v.to_string(),
            TExprKind::Str(s) => self.string_literal(s),
            TExprKind::Local(id) => {
                let r = self.fresh();
                let ty = llty(&self.locals[*id].ty);
                self.emit(format!("{r} = load {ty}, ptr %l{id}"));
                r
            }
            TExprKind::Call(fid, args) => {
                let mut vals = Vec::new();
                for a in args {
                    let v = self.expr(a);
                    vals.push(format!("{} {v}", llty(&a.ty)));
                }
                let f = &self.prog.funcs[*fid];
                if f.track_caller {
                    vals.push(self.loc(e.span));
                }
                let f = &self.prog.funcs[*fid];
                let sym = f.symbol.clone();
                if f.ret == Type::Unit {
                    self.emit(format!("call void @{sym}({})", vals.join(", ")));
                    String::new()
                } else {
                    let rt = llty(&f.ret);
                    let r = self.fresh();
                    self.emit(format!("{r} = call {rt} @{sym}({})", vals.join(", ")));
                    r
                }
            }
            TExprKind::Binary(op, l, r) => {
                let a = self.expr(l);
                let b = self.expr(r);
                self.binop_values(*op, &l.ty, &a, &b, e.span)
            }
            TExprKind::Neg(inner) => {
                let v = self.expr(inner);
                if inner.ty == Type::Int {
                    self.checked_int("ssub", "0", &v, e.span)
                } else {
                    let r = self.fresh();
                    self.emit(format!("{r} = fneg double {v}"));
                    r
                }
            }
            TExprKind::Not(inner) => {
                let v = self.expr(inner);
                let r = self.fresh();
                self.emit(format!("{r} = xor i1 {v}, true"));
                r
            }
            TExprKind::And(l, r) => self.short_circuit(true, l, r),
            TExprKind::Or(l, r) => self.short_circuit(false, l, r),
            TExprKind::Field(obj, sid, idx) => {
                let o = self.expr(obj);
                let s = &self.prog.structs[*sid];
                let sname = s.name.clone();
                let ft = llty(&s.fields[*idx].ty);
                let p = self.fresh();
                self.emit(format!("{p} = getelementptr inbounds %struct.{sname}, ptr {o}, i32 0, i32 {idx}"));
                let r = self.fresh();
                let md = self.field_tbaa(*sid, *idx);
                self.emit(format!("{r} = load {ft}, ptr {p}{md}"));
                r
            }
            TExprKind::Index(list, index) => {
                let l = self.expr(list);
                let i = self.expr(index);
                let p = self.list_elem_ptr(&l, &i, &e.ty, e.span);
                let r = self.fresh();
                let md = self.elem_tbaa(&e.ty);
                self.emit(format!("{r} = load {}, ptr {p}{md}", llty(&e.ty)));
                r
            }
            TExprKind::StructNew(sid, args) => {
                let vals: Vec<String> = args.iter().map(|a| self.expr(a)).collect();
                let sname = self.prog.structs[*sid].name.clone();
                let szp = self.fresh();
                self.emit(format!("{szp} = getelementptr %struct.{sname}, ptr null, i32 1"));
                let sz = self.fresh();
                self.emit(format!("{sz} = ptrtoint ptr {szp} to i64"));
                let p = self.fresh();
                self.emit(format!("{p} = call ptr @isma_alloc(i64 {sz})"));
                for (i, (v, a)) in vals.iter().zip(args).enumerate() {
                    let fp = self.fresh();
                    self.emit(format!("{fp} = getelementptr inbounds %struct.{sname}, ptr {p}, i32 0, i32 {i}"));
                    let md = self.field_tbaa(*sid, i);
                    self.emit(format!("store {} {v}, ptr {fp}{md}", llty(&a.ty)));
                }
                p
            }
            TExprKind::ListLit(elems) => {
                let elem = match &e.ty {
                    Type::List(t) => (**t).clone(),
                    _ => unreachable!(),
                };
                let sz = elem_size(&elem);
                let l = self.fresh();
                self.emit(format!("{l} = call ptr @isma_list_new(i64 {sz}, i64 {})", elems.len()));
                for el in elems {
                    let v = self.expr(el);
                    let slot = self.push_slot(&l, &elem);
                    let md = self.elem_tbaa(&elem);
                    self.emit(format!("store {} {v}, ptr {slot}{md}", llty(&elem)));
                }
                l
            }
            TExprKind::FString(parts) => {
                let mut acc: Option<String> = None;
                for p in parts {
                    let v = self.expr(p);
                    acc = Some(match acc {
                        None => v,
                        Some(prev) => {
                            let r = self.fresh();
                            self.emit(format!("{r} = call ptr @isma_str_concat(ptr {prev}, ptr {v})"));
                            r
                        }
                    });
                }
                acc.unwrap_or_else(|| self.string_literal(""))
            }
            TExprKind::Builtin(b, args) => self.builtin(*b, args, e),
        }
    }

    fn builtin(&mut self, b: Builtin, args: &[TExpr], e: &TExpr) -> String {
        let vals: Vec<String> = args.iter().map(|a| self.expr(a)).collect();
        let r = self.fresh();
        let loc = self.loc(e.span);
        match b {
            Builtin::Print => {
                let v = &vals[0];
                match &args[0].ty {
                    Type::Int => self.emit(format!("call void @isma_print_int(i64 {v})")),
                    Type::Float => self.emit(format!("call void @isma_print_float(double {v})")),
                    Type::Str => self.emit(format!("call void @isma_print_str(ptr {v})")),
                    Type::Bool => {
                        self.emit(format!("{r} = zext i1 {v} to i64"));
                        self.emit(format!("call void @isma_print_bool(i64 {r})"));
                    }
                    _ => unreachable!(),
                }
                return String::new();
            }
            Builtin::Input => self.emit(format!("{r} = call ptr @isma_input()")),
            Builtin::Args => self.emit(format!("{r} = call ptr @isma_args()")),
            Builtin::Panic => {
                self.emit(format!("call void @isma_panic_msg(ptr {}, {loc})", vals[0]));
                self.emit_term("unreachable");
                return String::new();
            }
            Builtin::Exit => {
                self.emit(format!("call void @isma_exit(i64 {})", vals[0]));
                self.emit_term("unreachable");
                return String::new();
            }
            Builtin::Assert => {
                let failed = self.fresh();
                self.emit(format!("{failed} = xor i1 {}, true", vals[0]));
                self.panic_if(&failed, format!("call void @isma_assert_fail({loc})"));
                return String::new();
            }
            Builtin::Sqrt => self.emit(format!("{r} = call double @llvm.sqrt.f64(double {})", vals[0])),
            Builtin::IntToFloat => self.emit(format!("{r} = sitofp i64 {} to double", vals[0])),
            Builtin::FloatToInt => self.emit(format!("{r} = call i64 @llvm.fptosi.sat.i64.f64(double {})", vals[0])),
            Builtin::StrToInt => self.emit(format!("{r} = call i64 @isma_str_to_int(ptr {}, {loc})", vals[0])),
            Builtin::StrToFloat => self.emit(format!("{r} = call double @isma_str_to_float(ptr {}, {loc})", vals[0])),
            Builtin::StrChars => self.emit(format!("{r} = call ptr @isma_str_chars(ptr {})", vals[0])),
            Builtin::StrSubstring => {
                self.emit(format!("{r} = call ptr @isma_str_substring(ptr {}, i64 {}, i64 {}, {loc})", vals[0], vals[1], vals[2]))
            }
            Builtin::StrContains | Builtin::StrStartsWith | Builtin::StrEndsWith => {
                let f = match b {
                    Builtin::StrContains => "isma_str_contains",
                    Builtin::StrStartsWith => "isma_str_starts_with",
                    _ => "isma_str_ends_with",
                };
                let raw = self.fresh();
                self.emit(format!("{raw} = call i64 @{f}(ptr {}, ptr {})", vals[0], vals[1]));
                self.emit(format!("{r} = icmp ne i64 {raw}, 0"));
            }
            Builtin::RealtimeNs => self.emit(format!("{r} = call i64 @isma_time_realtime_ns()")),
            Builtin::MonotonicNs => self.emit(format!("{r} = call i64 @isma_time_monotonic_ns()")),
            Builtin::SleepNs => {
                self.emit(format!("call void @isma_time_sleep_ns(i64 {})", vals[0]));
                return String::new();
            }
            Builtin::ToStr => return self.emit_to_string(&args[0].ty, &vals[0]),
            Builtin::StrLen => {
                let md = self.tbaa("str.len");
                self.emit(format!("{r} = load i64, ptr {}{md}", vals[0]));
            }
            Builtin::ListLen => {
                let md = self.tbaa("list.len");
                self.emit(format!("{r} = load i64, ptr {}{md}", vals[0]));
            }
            Builtin::ListPush => {
                let elem = args[1].ty.clone();
                let slot = self.push_slot(&vals[0], &elem);
                let md = self.elem_tbaa(&elem);
                self.emit(format!("store {} {}, ptr {slot}{md}", llty(&elem), vals[1]));
                return String::new();
            }
            Builtin::ListPop => {
                let sz = elem_size(&e.ty);
                let slot = self.fresh();
                self.emit(format!("{slot} = call ptr @isma_list_pop_slot(ptr {}, i64 {sz}, {loc})", vals[0]));
                let md = self.elem_tbaa(&e.ty);
                self.emit(format!("{r} = load {}, ptr {slot}{md}", llty(&e.ty)));
            }
        }
        r
    }
}
